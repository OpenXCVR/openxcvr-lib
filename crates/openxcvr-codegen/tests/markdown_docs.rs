//! Golden/exact-output tests for the Markdown reference emitter
//! (`--lang markdown`).
//!
//! The fixtures exercise the audited documentation requirements end to end:
//! lower-memory / page-11h-style revision metadata with `changed_in` /
//! `renamed_from` / `aliased_to` resolution, absent metadata rendered as
//! `not recorded`, both unit spellings, provenance citations, Markdown cell
//! escaping, enum rendering, and the schema-kind / namespace coverage
//! inventory.

use std::path::{Path, PathBuf};

use openxcvr_codegen::emitters::markdown;
use openxcvr_codegen::ir::pages::PageSchema;
use openxcvr_codegen::parser::index::IndexLoader;

fn temp_dir(name: &str) -> PathBuf {
    std::env::temp_dir().join(format!(
        "openxcvr-codegen-markdown-{name}-{}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos()
    ))
}

