/// Two consecutive `emit_tree` runs into separate directories must be
/// byte-identical — no timestamps, no run-dependent content.
#[test]
fn emit_tree_is_deterministic() {
    let root = temp_dir("determinism");
    let spec = root.join("spec");
    std::fs::create_dir_all(&spec).unwrap();
    std::fs::write(
        spec.join("_index.yaml"),
        "kind: memory_map\nspec:\n  id: spec\n  title: Spec\n  revision: \"1.0\"\nincludes:\n  - page.yaml\n  - enum.yaml\n",
    )
    .unwrap();
    std::fs::write(
        spec.join("page.yaml"),
        "schema: openxcvr.page.v2\nkind: page\nid: DetPage\ntitle: Det\npage_address: lower\nfields:\n  - { name: f, offset: 0, type: enum_ref, enum_ref: DetEnum, since: \"4.0\" }\n",
    )
    .unwrap();
    std::fs::write(
        spec.join("enum.yaml"),
        "schema: openxcvr.enum.v2\nkind: enum\nid: DetEnum\ntitle: Det Enum\nentries:\n  - { value: 0, name: zero, description: Zero }\n",
    )
    .unwrap();

    let enum_paths = IndexLoader::collect_enum_schemas(&root, Some("spec")).unwrap();
    let mut enums = Vec::new();
    for path in &enum_paths {
        enums.push((
            path.clone(),
            openxcvr_codegen::parser::enums::load_enum_schema(path).unwrap(),
        ));
    }
    let page_paths = IndexLoader::collect_page_schemas(&root, Some("spec")).unwrap();
    let mut pages = Vec::new();
    for path in &page_paths {
        pages.push((
            path.clone(),
            openxcvr_codegen::parser::pages::load_page_schema(path).unwrap(),
        ));
    }

    let out1 = root.join("out1");
    let out2 = root.join("out2");
    markdown::emit_tree(&root, Some("spec"), &out1, &enums, &pages).unwrap();
    markdown::emit_tree(&root, Some("spec"), &out2, &enums, &pages).unwrap();

    let dump = |dir: &Path| -> Vec<(PathBuf, Vec<u8>)> {
        let mut files: Vec<(PathBuf, Vec<u8>)> = walkdir::WalkDir::new(dir)
            .into_iter()
            .filter_map(|e| e.ok())
            .filter(|e| e.file_type().is_file())
            .filter_map(|e| {
                let path = e.path().strip_prefix(dir).unwrap().to_path_buf();
                Some((path, std::fs::read(e.path()).ok()?))
            })
            .collect();
        files.sort();
        files
    };
    assert_eq!(dump(&out1), dump(&out2), "two regens must be byte-equal");
    assert!(!dump(&out1).is_empty());
    std::fs::remove_dir_all(&root).ok();
}

