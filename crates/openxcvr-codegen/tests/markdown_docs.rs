/// The top-index probe (`markdown::index::emit_top_index`) is the second real
/// caller of the enum validation gate. A namespace whose enum carries invalid
/// revision metadata must be reported with an explicit `schemas fail
/// validation` reason carrying the enum diagnostic — not an invented error
/// return and not a clean-load claim (`probe_load` in `emitters/markdown/index.rs`).
#[test]
fn markdown_probe_reports_invalid_enum_metadata() {
    let root = temp_dir("invalid-enum-metadata");
    let spec = root.join("metaspec");
    std::fs::create_dir_all(&spec).unwrap();
    std::fs::write(
        spec.join("_index.yaml"),
        "kind: memory_map\nspec: { id: metaspec, title: Meta Spec }\nincludes: [enum.yaml, page.yaml]\n",
    )
    .unwrap();
    // A valid page schema keeps the probe's page validation clean, so the
    // only thing under test is the enum metadata gate.
    std::fs::write(
        spec.join("page.yaml"),
        "schema: openxcvr.page.v1\nkind: page\nid: MetaPage\ntitle: Meta Page\npage_address: lower\nfields:\n  - { name: f, offset: 0, type: u8 }\n",
    )
    .unwrap();
    std::fs::write(
        spec.join("enum.yaml"),
        "schema: openxcvr.enum.v2\nkind: enum\nid: MetaEnum\ntitle: Meta Enum\nspec:\n  id: cmis\n  revision: \"5.3\"\nentries:\n  - value: 0x5\n    name: dp_tx_turn_on\n    since: \"5.5\"\n",
    )
    .unwrap();
    let out = root.join("out");
    let index = markdown::index::emit_top_index(&root, &out).unwrap();
    assert!(
        index.contains("not rendered — schemas fail validation"),
        "probe must report the failure reason verbatim:\n{index}"
    );
    for token in ["MetaEnum", "dp_tx_turn_on", "since", "5.5"] {
        assert!(
            index.contains(token),
            "probe reason must carry the enum diagnostic ({token}):\n{index}"
        );
    }
    assert!(
        !index.contains("load and validate cleanly"),
        "invalid metadata must never be reported as a clean load:\n{index}"
    );
    std::fs::remove_dir_all(&root).ok();
}

/// Windowed families publish the codegen revision domain, not the index's
/// single document revision. `sff-8472` document revision `12.5a` stays the
/// cited label; the runtime label is the domain member `12.5`.
#[test]
fn windowed_family_indexes_list_the_revision_domain() {
    let root = temp_dir("revision-domain");
    for (name, revision, source) in [
        ("cmis", "5.4", "docs/stds/cmis/OIF-CMIS-05.4.pdf"),
        (
            "sff-8472",
            "12.5a",
            "docs/stds/sff-8472/SFF-8472-Rev12.5a.pdf",
        ),
        ("extra-ns", "01.0", "docs/stds/extra.pdf"),
    ] {
        let spec = root.join(name);
        std::fs::create_dir_all(&spec).unwrap();
        std::fs::write(
            spec.join("_index.yaml"),
            format!(
                "schema: openxcvr.schema_index.v1\nkind: memory_map\nspec:\n  id: {name}\n  title: {name}\n  revision: \"{revision}\"\n  source: {source}\nincludes:\n  - page.yaml\n"
            ),
        )
        .unwrap();
        std::fs::write(
            spec.join("page.yaml"),
            format!(
                "schema: openxcvr.page.v2\nkind: page\nid: {name}Page\ntitle: {name} Page\npage_address: lower\nfields:\n  - {{ name: flag, offset: 0, type: u8 }}\n"
            ),
        )
        .unwrap();
    }

    let out = root.join("reference");
    for spec in ["cmis", "sff-8472", "extra-ns"] {
        let page_paths = IndexLoader::collect_page_schemas(&root, Some(spec)).unwrap();
        let mut pages = Vec::new();
        for path in &page_paths {
            pages.push((
                path.clone(),
                openxcvr_codegen::parser::pages::load_page_schema(path).unwrap(),
            ));
        }
        markdown::emit_tree(&root, Some(spec), &out, &[], &pages).unwrap();
    }

    let cmis = std::fs::read_to_string(out.join("cmis").join("index.md")).unwrap();
    assert!(
        cmis.contains(
            "- Modelled revisions: `3.0, 4.0, 5.0, 5.1, 5.2, 5.3, 5.4` (codegen revision domain for this family; not a single revision)"
        ),
        "cmis modelled revisions missing:\n{cmis}"
    );
    assert!(
        cmis.contains("Document revision: `5.4`, source `docs/stds/cmis/OIF-CMIS-05.4.pdf`"),
        "cmis document revision missing:\n{cmis}"
    );
    assert!(
        !cmis.contains("Runtime revision:"),
        "a document revision inside the domain needs no runtime alias:\n{cmis}"
    );

    let sff = std::fs::read_to_string(out.join("sff-8472").join("index.md")).unwrap();
    assert!(
        sff.contains(
            "- Modelled revisions: `9.3, 9.5, 10.2, 10.4, 11.0, 11.3, 11.4, 12.3, 12.4, 12.5`"
        ),
        "sff-8472 domain missing:\n{sff}"
    );
    assert!(
        sff.contains("- Runtime revision: `12.5`. Document revision `12.5a` is the cited specification's label and is not a runtime revision label."),
        "sff-8472 runtime label missing:\n{sff}"
    );

    let top = std::fs::read_to_string(out.join("index.md")).unwrap();
    assert!(
        top.contains(
            "| [`cmis`](cmis/index.md) | cmis | `3.0, 4.0, 5.0, 5.1, 5.2, 5.3, 5.4` | rendered |"
        ),
        "top index must list the cmis domain, not only the document revision:\n{top}"
    );
    assert!(
        top.contains("| [`sff-8472`](sff-8472/index.md) | sff-8472 | `9.3, 9.5, 10.2, 10.4, 11.0, 11.3, 11.4, 12.3, 12.4, 12.5` | rendered |"),
        "top index must list runtime revisions, not 12.5a:\n{top}"
    );
    assert!(
        top.contains("| [`extra-ns`](extra-ns/index.md) | extra-ns | `01.0` | rendered |"),
        "a companion namespace keeps its single document revision:\n{top}"
    );

    std::fs::remove_dir_all(&root).ok();
}

