use clap::{Parser, Subcommand};
use std::path::PathBuf;

use openxcvr_codegen::emitters::c::CEmitter;
use openxcvr_codegen::emitters::csharp::CSharpEmitter;
use openxcvr_codegen::emitters::go::GoEmitter;
use openxcvr_codegen::emitters::java::JavaEmitter;
use openxcvr_codegen::emitters::openapi::OpenApiEmitter;
use openxcvr_codegen::emitters::php::PhpEmitter;
use openxcvr_codegen::emitters::python::PythonEmitter;
use openxcvr_codegen::emitters::rust::RustEmitter;
use openxcvr_codegen::emitters::typescript::TypeScriptEmitter;
use openxcvr_codegen::emitters::Emitter;
use openxcvr_codegen::ir::naming::{camel_to_snake, JavaNaming, NamingPolicy};
use openxcvr_codegen::parser;
use openxcvr_codegen::validator;

#[derive(Parser)]
#[command(name = "openxcvr", about = "openxcvr schema codegen tool")]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    Generate {
        #[arg(long, default_value = "schemas")]
        schemas: PathBuf,
        #[arg(long)]
        spec: Option<String>,
        #[arg(long, default_value = "generated")]
        out: PathBuf,
        /// Output language: rust (default), python, go, php, c, typescript, java, csharp, openapi, or markdown
        #[arg(long, default_value = "rust")]
        lang: String,
    },
}

/// Write the C umbrella header by scanning the output `enums/` and `pages/`
/// directories. Scanning the directory (rather than only the ids generated in
/// this invocation) makes the umbrella complete when multiple specs are
/// generated into one directory via separate `--spec` runs — matching how every
/// other binding accumulates per-spec files into one output tree.
fn write_c_umbrella(out: &std::path::Path) -> anyhow::Result<()> {
    let mut code =
        String::from("/* Generated by openxcvr-codegen. DO NOT EDIT. */\n#pragma once\n\n");
    for sub in ["enums", "pages", "catalog", "fsm"] {
        let dir = out.join(sub);
        if !dir.exists() {
            continue;
        }
        let mut stems: Vec<String> = std::fs::read_dir(&dir)?
            .filter_map(|e| e.ok())
            .filter_map(|e| {
                let p = e.path();
                if p.extension().and_then(|s| s.to_str()) == Some("h") {
                    p.file_stem().and_then(|s| s.to_str()).map(String::from)
                } else {
                    None
                }
            })
            .collect();
        stems.sort();
        for stem in stems {
            code.push_str(&format!("#include \"{sub}/{stem}.h\"\n"));
        }
    }
    std::fs::write(out.join("openxcvr_generated.h"), code)?;
    Ok(())
}

fn main() -> anyhow::Result<()> {
    let cli = Cli::parse();

    match cli.command {
        Commands::Generate {
            schemas,
            spec,
            out,
            lang,
        } => {
            if !matches!(
                lang.as_str(),
                "rust"
                    | "python"
                    | "go"
                    | "php"
                    | "c"
                    | "typescript"
                    | "java"
                    | "csharp"
                    | "openapi"
                    | "markdown"
            ) {
                anyhow::bail!(
                    "unsupported --lang {lang:?}; expected rust, python, go, php, c, typescript, java, csharp, openapi, or markdown"
                );
            }
            let rust_mode = lang == "rust";
            let python_mode = lang == "python";
            let go_mode = lang == "go";
            let php_mode = lang == "php";
            let c_mode = lang == "c";
            let ts_mode = lang == "typescript";
            let java_mode = lang == "java";
            let csharp_mode = lang == "csharp";
            let openapi_mode = lang == "openapi";
            let markdown_mode = lang == "markdown";

            std::fs::create_dir_all(&out)?;
            if python_mode || go_mode || ts_mode {
                std::fs::create_dir_all(out.join("enums"))?;
            }
            if c_mode || openapi_mode {
                std::fs::create_dir_all(out.join("enums"))?;
                std::fs::create_dir_all(out.join("pages"))?;
            }
            if php_mode {
                std::fs::create_dir_all(out.join("Enums"))?;
            }

            // --- Enum schemas ---
            let enum_paths =
                parser::index::IndexLoader::collect_enum_schemas(&schemas, spec.as_deref())?;

            // (source path, schema) pairs — the markdown tree emitter groups
            // output by the spec directory that owns each schema file.
            let mut enum_pairs = Vec::new();
            let mut load_errors = Vec::new();
            for path in &enum_paths {
                match parser::enums::load_enum_schema(path) {
                    Ok(schema) => enum_pairs.push((path.clone(), schema)),
                    Err(e) => load_errors.push(format!("{}: {:#}", path.display(), e)),
                }
            }
            if !load_errors.is_empty() {
                anyhow::bail!(
                    "failed to load {} enum schema(s):\n{}",
                    load_errors.len(),
                    load_errors.join("\n")
                );
            }
            let enum_schemas: Vec<openxcvr_codegen::ir::enums::EnumSchema> =
                enum_pairs.iter().map(|(_, s)| s.clone()).collect();

            validator::validate_enums(&enum_schemas)?;

            // --- Page schemas ---
            let page_paths =
                parser::index::IndexLoader::collect_page_schemas(&schemas, spec.as_deref())?;

            let mut page_pairs = Vec::new();
            let mut load_errors = Vec::new();
            for path in &page_paths {
                match parser::pages::load_page_schema(path) {
                    Ok(schema) => page_pairs.push((path.clone(), schema)),
                    Err(e) => load_errors.push(format!("{}: {:#}", path.display(), e)),
                }
            }
            if !load_errors.is_empty() {
                anyhow::bail!(
                    "failed to load {} page schema(s):\n{}",
                    load_errors.len(),
                    load_errors.join("\n")
                );
            }
            let page_schemas: Vec<openxcvr_codegen::ir::pages::PageSchema> =
                page_pairs.iter().map(|(_, s)| s.clone()).collect();

            validator::validate_pages(&page_schemas)?;
            validator::validate_page_enum_refs(&page_schemas, &enum_schemas)?;

            // --- State-machine schemas ---
            // Collected from the `state_machines:` index key for every
            // language run; parity against the enum registries is checked
            // through the same emission path the Rust tables come from, so
            // every run fails loud on a machine/enum mismatch before any
            // output is written.
            let state_machine_paths = parser::index::IndexLoader::collect_state_machine_schemas(
                &schemas,
                spec.as_deref(),
            )?;
            let mut state_machine_schemas = Vec::new();
            let mut load_errors = Vec::new();
            for path in &state_machine_paths {
                match parser::state_machines::load_state_machine_schema(path) {
                    Ok(schema) => state_machine_schemas.push(schema),
                    Err(e) => load_errors.push(format!("{}: {:#}", path.display(), e)),
                }
            }
            if !load_errors.is_empty() {
                anyhow::bail!(
                    "failed to load {} state machine schema(s):\n{}",
                    load_errors.len(),
                    load_errors.join("\n")
                );
            }
            let mut rust_machine_outputs = Vec::new();
            for schema in &state_machine_schemas {
                let code =
                    openxcvr_codegen::emitters::rust::state_machines::emit_state_machine_rust(
                        schema,
                        &enum_schemas,
                    )?;
                // Every language validates here; Rust also reuses the rendered
                // output after all preflight checks have succeeded.
                if rust_mode {
                    rust_machine_outputs.push((camel_to_snake(&schema.id), code));
                }
            }
            // Stage 1 B1: classify field-level present_when fail-loud for
            // every language run, not only the catalog emitters — grouped by
            // each page's OWNING namespace (the spec directory that owns the
            // file), not the requested --spec. A supplement run (e.g.
            // --spec c-cmis-1.4) imports ../cmis/_index.yaml; those pages
            // classify under their own family, and supplement namespaces
            // without a family may not declare present_when at all. Runs
            // with --spec omitted validate exactly the same way.
            let info = openxcvr_codegen::emitters::rust::catalog::page_catalog_info(&page_paths)
                .map_err(|e| anyhow::anyhow!("{e}"))?;
            openxcvr_codegen::presence::validate_presence_by_namespace(
                &schemas,
                &page_pairs,
                &info,
            )
            .map_err(|e| anyhow::anyhow!("presence classification: {e}"))?;

            // Preflight ALL checked pages before writing ANY checked output.
            // A representability error is a CLI failure, not a dropped member.
            // Target selection stays derived: for CMIS, the settled curated
            // page set; for the SFF families, every family-owned versioned
            // page (the same derived rule the Python emitter uses).
            let mut checked_pages = Vec::new();
            if c_mode {
                let family = openxcvr_codegen::emitters::rust::catalog::spec_family(
                    spec.as_deref().unwrap_or(""),
                );
                if let Some(family) = family {
                    let cmis = family.spec == "cmis";
                    for (path, schema) in &page_pairs {
                        let namespace = openxcvr_codegen::presence::namespace_of(&schemas, path);
                        let selected = namespace.as_deref() == Some(family.spec)
                            && (cmis
                                && openxcvr_codegen::emitters::c::revision::CHECKED_PAGE_IDS
                                    .contains(&schema.id.as_str())
                                || !cmis
                                    && openxcvr_codegen::emitters::rust::pages::is_versioned(
                                        schema,
                                    ));
                        if selected {
                            use openxcvr_codegen::emitters::c::revision::plan_checked_page;
                            let stem = format!("{}_revision", camel_to_snake(&schema.id));
                            match plan_checked_page(schema, &format!("pages/{stem}.h")) {
                                Ok(planned) => checked_pages.push((stem, planned)),
                                // A page the shared C extraction cannot yet
                                // represent (e.g. a 16-bit enum_ref) is
                                // excluded from the additive checked surface,
                                // never silently: the run names page and
                                // reason. Raw pages and other languages are
                                // unaffected.
                                Err(reason) if !cmis => {
                                    eprintln!("checked C page skipped ({}): {reason}", schema.id)
                                }
                                Err(reason) => {
                                    return Err(anyhow::anyhow!(
                                        "checked page {}: {reason}",
                                        schema.id
                                    ))
                                }
                            }
                        }
                    }
                }
            }

            // Preflight ALL checked Python pages before writing ANY output file
            // of this invocation (raw enums, pages and the media helper
            // included): a planning or emission error must leave the whole
            // output tree untouched, with no partial generated files. Target
            // selection is derived, never hand-listed: every page owned by a
            // modeled family namespace (cmis, sff-8636, sff-8472 — the spec
            // directory owning its schema file) that carries field-version
            // metadata (`is_versioned`) gets a checked sibling; unversioned
            // pages and every other namespace get none.
            let mut checked_python_outputs = Vec::new();
            if python_mode {
                for (path, schema) in &page_pairs {
                    let namespace = openxcvr_codegen::presence::namespace_of(&schemas, path);
                    let family = namespace
                        .as_deref()
                        .and_then(openxcvr_codegen::emitters::rust::catalog::spec_family);
                    if family.is_none() {
                        continue;
                    }
                    if !openxcvr_codegen::emitters::rust::pages::is_versioned(schema) {
                        continue;
                    }
                    let planned = openxcvr_codegen::ir::checked::plan_checked_page(schema)
                        .map_err(anyhow::Error::msg)?;
                    let code =
                        openxcvr_codegen::emitters::python::emit_checked_page(schema, &planned)
                            .map_err(anyhow::Error::msg)?;
                    let stem = format!("{}_revision", camel_to_snake(&schema.id));
                    checked_python_outputs.push((stem, code));
                }
            }

            if markdown_mode {
                // The Markdown reference tree is emitted from the same IR and
                // revision resolver as every other language; it has its own
                // multi-file layout, so it bypasses the per-schema emit loops.
                openxcvr_codegen::emitters::markdown::emit_tree(
                    &schemas,
                    spec.as_deref(),
                    &out,
                    &enum_pairs,
                    &page_pairs,
                )?;
                println!(
                    "Generated markdown reference to {} ({} enum(s), {} page(s), lang={})",
                    out.display(),
                    enum_pairs.len(),
                    page_pairs.len(),
                    lang,
                );
                return Ok(());
            }

            let emitter: &dyn Emitter = match lang.as_str() {
                "python" => &PythonEmitter,
                "go" => &GoEmitter,
                "php" => &PhpEmitter,
                "c" => &CEmitter,
                "typescript" => &TypeScriptEmitter,
                "java" => &JavaEmitter,
                "csharp" => &CSharpEmitter,
                "openapi" => &OpenApiEmitter,
                _ => &RustEmitter,
            };
            for (_, schema) in &enum_pairs {
                let code = emitter.emit_enum(schema);
                let out_file = if python_mode {
                    out.join("enums")
                        .join(format!("{}.py", camel_to_snake(&schema.id)))
                } else if go_mode {
                    out.join("enums")
                        .join(format!("{}.go", camel_to_snake(&schema.id)))
                } else if php_mode {
                    out.join("Enums").join(format!("{}.php", schema.id))
                } else if c_mode {
                    out.join("enums")
                        .join(format!("{}.h", camel_to_snake(&schema.id)))
                } else if ts_mode {
                    out.join("enums")
                        .join(format!("{}.ts", camel_to_snake(&schema.id)))
                } else if java_mode {
                    // Java requires the public type and the filename to match.
                    // type_name is PascalCase; schema.id is not always (the six SFF-8472 pages).
                    out.join(format!("{}.java", JavaNaming.type_name(&schema.id)))
                } else if csharp_mode {
                    out.join(format!("{}.cs", schema.id))
                } else if openapi_mode {
                    out.join("enums")
                        .join(format!("{}.schema.json", camel_to_snake(&schema.id)))
                } else {
                    out.join(format!("{}.rs", schema.id))
                };
                std::fs::write(&out_file, &code)?;
            }

            let media_plan =
                openxcvr_codegen::media_interface::plan_from_schemas(&page_schemas, &enum_schemas)?;
            if let Some(ref plan) = media_plan {
                if python_mode {
                    std::fs::write(
                        out.join("enums").join("cmis_media_interface.py"),
                        openxcvr_codegen::emitters::python::emit_media_interface(plan),
                    )?;
                } else if go_mode {
                    std::fs::write(
                        out.join("enums").join("cmis_media_interface.go"),
                        openxcvr_codegen::emitters::go::emit_media_interface(plan),
                    )?;
                } else if php_mode {
                    std::fs::write(
                        out.join("Enums").join("CmisMediaInterface.php"),
                        openxcvr_codegen::emitters::php::emit_media_interface(plan),
                    )?;
                } else if c_mode {
                    std::fs::write(
                        out.join("enums").join("cmis_media_interface.h"),
                        openxcvr_codegen::emitters::c::emit_media_interface(plan),
                    )?;
                } else if ts_mode {
                    std::fs::write(
                        out.join("enums").join("cmis_media_interface.ts"),
                        openxcvr_codegen::emitters::typescript::emit_media_interface(plan),
                    )?;
                } else if java_mode {
                    // Java requires the public class and the filename to match.
                    std::fs::write(
                        out.join("CmisMediaInterface.java"),
                        openxcvr_codegen::emitters::java::emit_media_interface(plan),
                    )?;
                } else if csharp_mode {
                    std::fs::write(
                        out.join("CmisMediaInterface.cs"),
                        openxcvr_codegen::emitters::csharp::emit_media_interface(plan),
                    )?;
                }
            }

            for (_, schema) in &page_pairs {
                if c_mode {
                    let file_stem = camel_to_snake(&schema.id);
                    let header_rel = format!("pages/{file_stem}.h");
                    let header = CEmitter.emit_page_header(schema);
                    let source = CEmitter.emit_page_source(schema, &header_rel);
                    std::fs::write(out.join(&header_rel), header)?;
                    std::fs::write(out.join("pages").join(format!("{file_stem}.c")), source)?;
                    continue;
                }
                if rust_mode {
                    // Rust: per-rev dispatch if any field carries version metadata;
                    // otherwise single unversioned file. emit_page_dispatched handles
                    // directory creation and writing.
                    openxcvr_codegen::emitters::rust::pages::emit_page_dispatched(schema, &out)?;
                    continue;
                }
                let code = emitter.emit_page(schema);
                let out_file = if python_mode {
                    out.join(format!("{}.py", camel_to_snake(&schema.id)))
                } else if go_mode {
                    out.join(format!("{}.go", camel_to_snake(&schema.id)))
                } else if php_mode {
                    out.join(format!("{}.php", schema.id))
                } else if ts_mode {
                    out.join(format!("{}.ts", camel_to_snake(&schema.id)))
                } else if java_mode {
                    out.join(format!("{}.java", JavaNaming.type_name(&schema.id)))
                } else if csharp_mode {
                    out.join(format!("{}.cs", schema.id))
                } else {
                    out.join("pages")
                        .join(format!("{}.schema.json", camel_to_snake(&schema.id)))
                };
                std::fs::write(&out_file, &code)?;
            }

            // Checked Python siblings join the same flat generated tree as
            // the raw pages; they were all planned and rendered above, before
            // any output file of this invocation was written.
            if python_mode {
                for (stem, code) in &checked_python_outputs {
                    std::fs::write(out.join(format!("{stem}.py")), code)?;
                }
            }

            if c_mode {
                // Field-catalog table (P-OBS basic/catalog): one header and
                // source pair per spec under catalog/.
                if openxcvr_codegen::emitters::rust::catalog::spec_family(
                    spec.as_deref().unwrap_or(""),
                )
                .is_some()
                {
                    let stem = spec.as_deref().unwrap_or("").replace('-', "");
                    let header = openxcvr_codegen::emitters::c::catalog::emit_catalog_c_header(
                        spec.as_deref().unwrap_or(""),
                        &page_schemas,
                        &info,
                    )
                    .map_err(|e| anyhow::anyhow!("catalog emission: {e}"))?;
                    let source = openxcvr_codegen::emitters::c::catalog::emit_catalog_c_source(
                        spec.as_deref().unwrap_or(""),
                        &page_schemas,
                        &info,
                    )
                    .map_err(|e| anyhow::anyhow!("catalog emission: {e}"))?;
                    std::fs::create_dir_all(out.join("catalog"))?;
                    std::fs::write(
                        out.join("catalog").join(format!("{stem}_catalog.h")),
                        header,
                    )?;
                    std::fs::write(
                        out.join("catalog").join(format!("{stem}_catalog.c")),
                        source,
                    )?;
                }
                for (stem, planned) in checked_pages {
                    std::fs::write(out.join("pages").join(format!("{stem}.h")), planned.header)?;
                    std::fs::write(out.join("pages").join(format!("{stem}.c")), planned.source)?;
                }
                // Internal behaviour tables: one
                // header/source pair per state-machine schema under fsm/,
                // plus the shared descriptor header the pairs include. Only
                // a spec whose index carries state machines writes anything
                // here; emission itself fails loud on a machine/enum
                // mismatch, exactly like the Rust stream.
                if !state_machine_schemas.is_empty() {
                    let fsm_dir = out.join("fsm");
                    std::fs::create_dir_all(&fsm_dir)?;
                    std::fs::write(
                        fsm_dir.join("behaviour_tables.h"),
                        openxcvr_codegen::emitters::c::emit_shared_types_header(),
                    )?;
                    for schema in &state_machine_schemas {
                        let stem = camel_to_snake(&schema.id);
                        let header = openxcvr_codegen::emitters::c::emit_state_machine_c_header(
                            schema,
                            &enum_schemas,
                        )?;
                        let source = openxcvr_codegen::emitters::c::emit_state_machine_c_source(
                            schema,
                            &enum_schemas,
                        )?;
                        std::fs::write(fsm_dir.join(format!("{stem}.h")), header)?;
                        std::fs::write(fsm_dir.join(format!("{stem}.c")), source)?;
                    }
                }
                write_c_umbrella(&out)?;
            }

            if rust_mode {
                // Wire the tree: generated/mod.rs plus one mod.rs per revision
                // directory, so a regen never needs hand-maintained module
                // declarations (see emitters::rust::module).
                use openxcvr_codegen::emitters::rust::module::{emit_mod_rs, emit_rev_mod_rs};
                use openxcvr_codegen::emitters::rust::pages::is_versioned;
                use openxcvr_codegen::ir::version::Rev;
                let spec_name = spec.as_deref().unwrap_or("<spec>");
                let mut enum_ids: Vec<String> = enum_schemas.iter().map(|s| s.id.clone()).collect();
                enum_ids.sort();
                let mut page_ids: Vec<String> = page_schemas.iter().map(|s| s.id.clone()).collect();
                page_ids.sort();
                let mut versioned_ids: Vec<String> = page_schemas
                    .iter()
                    .filter(|s| is_versioned(s))
                    .map(|s| s.id.clone())
                    .collect();
                versioned_ids.sort();
                // Per-revision directory set: the family domain the
                // generated spec names (CMIS for spec-less union runs),
                // empty when nothing is versioned.
                let revs: &[Rev] = if versioned_ids.is_empty() {
                    &[]
                } else {
                    openxcvr_codegen::ir::version::family_revs_for_spec(Some(spec_name))
                };
                // State-machine behaviour tables: one
                // module per machine under generated/fsm/, plus the fsm/
                // mod.rs wiring. Machines absent from the spec's index emit
                // nothing, and generated/mod.rs declares `pub mod fsm;`
                // only when at least one was collected.
                let mut fsm_machine_ids: Vec<String> =
                    state_machine_schemas.iter().map(|s| s.id.clone()).collect();
                fsm_machine_ids.sort();
                if !fsm_machine_ids.is_empty() {
                    let fsm_dir = out.join("fsm");
                    std::fs::create_dir_all(&fsm_dir)?;
                    for (stem, code) in rust_machine_outputs {
                        std::fs::write(fsm_dir.join(format!("{stem}.rs")), code)?;
                    }
                    std::fs::write(
                        fsm_dir.join("mod.rs"),
                        openxcvr_codegen::emitters::rust::state_machines::emit_fsm_mod_rs(
                            spec_name,
                            &fsm_machine_ids,
                        ),
                    )?;
                }
                std::fs::write(
                    out.join("mod.rs"),
                    emit_mod_rs(
                        spec_name,
                        &enum_ids,
                        &page_ids,
                        &versioned_ids,
                        revs,
                        &fsm_machine_ids,
                    ),
                )?;
                for rev in revs {
                    std::fs::write(
                        out.join(format!("v{}", rev.dirname())).join("mod.rs"),
                        emit_rev_mod_rs(spec_name, *rev, &enum_ids, &versioned_ids),
                    )?;
                }
                // Field-catalog table (P-OBS basic/catalog): emitted for the
                // three known families; generated/mod.rs declares it only for
                // the same set, so no-spec (union) runs stay consistent.
                if openxcvr_codegen::emitters::rust::catalog::spec_family(spec_name).is_some() {
                    let catalog = openxcvr_codegen::emitters::rust::catalog::emit_catalog(
                        spec_name,
                        &page_schemas,
                        &info,
                    )
                    .map_err(|e| anyhow::anyhow!("catalog emission: {e}"))?;
                    std::fs::write(out.join("catalog.rs"), catalog)?;
                }
            }

            println!(
                "Generated {} enum(s) + {} page(s) to {} (lang={})",
                enum_pairs.len(),
                page_pairs.len() + checked_python_outputs.len(),
                out.display(),
                lang,
            );
            Ok(())
        }
    }
}
