//! `mod.rs` wiring for the Rust `generated/` tree.
//!
//! The enum and page emitters write one PascalCase `.rs` file per schema id;
//! Rust module names are snake_case, so every file needs a `#[path]`-mapped
//! `pub mod` plus a glob re-export. Versioned pages additionally
//! get one specialised copy per CMIS revision under `v{rev}/`, each with its
//! own `mod.rs` that re-exports the flat enums the page files reach through
//! `use super::*`.
//!
//! Emitting these files from the generator keeps `generated/` reproducible:
//! `tools/regen-rust.sh` must leave a clean tree, with no hand-maintained
//! wiring to keep in lock-step.

use crate::ir::naming::camel_to_snake;
use crate::ir::version::Rev;

const HEADER: &str = "// Generated by openxcvr-codegen. DO NOT EDIT.\n";
const ALLOW: &str = "#![allow(non_snake_case, dead_code, unused_imports, clippy::all)]\n";

fn rule(title: &str) -> String {
    // Keep the rule at 78 columns like the rest of the generated headers.
    let head = format!("// ── {title} ");
    let pad = 78usize.saturating_sub(head.chars().count());
    format!("{head}{}\n", "─".repeat(pad))
}

fn wire(ids: &[String], out: &mut String) {
    for id in ids {
        out.push_str(&format!(
            "#[path = \"{id}.rs\"]\npub mod {snake};\npub use {snake}::*;\n\n",
            snake = camel_to_snake(id)
        ));
    }
}

/// Declare a file-backed module PRIVATELY, without re-exporting its contents.
///
/// Private is the point. Emitting `pub mod cmis_lower_memory;` left the union
/// reachable as `generated::cmis_lower_memory::CmisLowerMemory` — a path that
/// names no union and carries no warning — so withholding the glob re-export
/// restricted the namespace by convention only. A consumer whose flat import
/// broke could "fix" it by reaching through the backing module and silently get
/// the all-revisions union back.
///
/// The module stays visible to `generated`'s own descendants (`union`, and the
/// per-revision `v{rev}` trees), which is exactly who needs it.
fn declare(ids: &[String], out: &mut String) {
    for id in ids {
        out.push_str(&format!(
            "#[path = \"{id}.rs\"]\nmod {snake};\n",
            snake = camel_to_snake(id)
        ));
    }
}

/// Top-level `generated/mod.rs`.
///
/// `enum_ids` and the *unversioned* members of `page_ids` are wired flat, so
/// `use generated::*` yields exactly the types that mean the same thing at
/// every CMIS revision.
///
/// Versioned pages are deliberately NOT glob re-exported. Their flat file is
/// the union of every field across every revision, so reaching one through the
/// default path silently hands a CMIS 3.0 consumer fields that only exist since
/// 5.0 — and, symmetrically, fields removed at 4.0. They are reachable at
/// `generated::union::*`, which forces a caller to name the union it is asking
/// for, and at `generated::v{rev}::*`, which is revision-correct. Page 9Fh
/// preserves its already-public flat codec paths: only its read-effect evidence
/// gained revision metadata, not its codec fields.
///
/// `revs` is the per-revision directory set to declare (empty when the spec has
/// no versioned page).
pub fn emit_mod_rs(
    spec: &str,
    enum_ids: &[String],
    page_ids: &[String],
    versioned_ids: &[String],
    revs: &[Rev],
    fsm_machine_ids: &[String],
) -> String {
    let unversioned: Vec<String> = page_ids
        .iter()
        .filter(|id| !versioned_ids.contains(id))
        .cloned()
        .collect();

    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str(&format!("// Regenerate with: tools/regen-rust.sh {spec}\n"));
    out.push_str(ALLOW);
    out.push('\n');

    out.push_str(&rule("Enums"));
    out.push('\n');
    wire(enum_ids, &mut out);

    out.push_str(&rule("Pages"));
    out.push('\n');
    wire(&unversioned, &mut out);

    if crate::emitters::rust::catalog::spec_family(spec).is_some() {
        out.push_str(&rule("Field catalog"));
        out.push_str(
            "// Schema-derived field metadata table (P-OBS basic/catalog),\n\
             // emitted for every known-spec rust-mode run.\n",
        );
        out.push_str("pub mod catalog;\n\n");
    }

    if !versioned_ids.is_empty() {
        out.push_str(&rule("Versioned pages — union view"));
        out.push_str(
            "// These pages carry page.v2 version metadata, so their flat file is the\n\
             // UNION of every field across every revision: a field marked since:5.0\n\
             // sits alongside one removed at 4.0, and nothing at the type level says\n\
             // which of them is real for the module actually in front of you.\n\
             //\n\
             // They are therefore declared but NOT glob re-exported: `use generated::*`\n\
             // must not hand a caller a union by accident. Reach them explicitly at\n\
             // `generated::union::<Page>` when a rev-agnostic view is genuinely wanted,\n\
             // or — preferably — at `generated::v{rev}::<Page>`, which is specialised\n\
             // to one revision and cannot over-report.\n",
        );
        out.push('\n');
        // Page 9Fh acquired revision-specific read-effect evidence after its
        // flat public codec shipped. Preserve both old paths; no codec field
        // differs by revision, only the new qualification metadata does.
        let private_ids: Vec<_> = versioned_ids
            .iter()
            .filter(|id| id.as_str() != "CmisPage9FhCdbMessage")
            .cloned()
            .collect();
        declare(&private_ids, &mut out);
        if versioned_ids.iter().any(|id| id == "CmisPage9FhCdbMessage") {
            out.push_str("// Compatibility: the existing flat Page 9Fh codec remains public.\n");
            wire(&["CmisPage9FhCdbMessage".to_owned()], &mut out);
        }
        out.push('\n');
        out.push_str(
            "/// Rev-agnostic union view of every versioned page. Naming this module\n\
             /// is the caller asserting they want the union and will interpret its\n\
             /// fields against a revision they establish some other way.\n\
             pub mod union {\n",
        );
        for id in versioned_ids {
            out.push_str(&format!(
                "    pub use super::{snake}::*;\n",
                snake = camel_to_snake(id)
            ));
        }
        out.push_str("}\n");
    }

    if !fsm_machine_ids.is_empty() {
        out.push_str(&rule("State machines"));
        out.push_str(
            "// Revision-aware behaviour tables generated from the spec's
             // state-machines/*.yaml schemas: plain data the daemon (and, per the
             // pinning rule, the kernel module) consumes. The kernel UAPI/ABI stays in
             // the kernel module; this tree emits data only.
",
        );
        out.push_str(
            "pub mod fsm;

",
        );
    }

    if !revs.is_empty() {
        out.push_str(&rule("Per-revision pages"));
        out.push_str(
            "// Pages carrying page.v2 version metadata are emitted once per\n\
             // revision under `v{rev}/`, fully specialised, for rev-aware consumers.\n\
             // Prefer these over the union view above.\n",
        );
        for rev in revs {
            out.push_str(&format!("pub mod v{};\n", rev.dirname()));
        }
    }
    out
}

/// `generated/v{rev}/mod.rs`: wire the per-revision page files and re-export
/// the flat enums (the page files resolve them through `use super::*`).
pub fn emit_rev_mod_rs(spec: &str, rev: Rev, enum_ids: &[String], page_ids: &[String]) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str(&format!("// Regenerate with: tools/regen-rust.sh {spec}\n"));
    out.push_str(&format!(
        "// Revision-specialised pages for {} {}. The page files do\n\
         // `use super::*`, so the flat enums are re-exported here.\n",
        spec.to_uppercase(),
        rev.as_str()
    ));
    out.push_str(ALLOW);
    out.push('\n');

    if !enum_ids.is_empty() {
        out.push_str("pub use super::{\n");
        for id in enum_ids {
            out.push_str(&format!("    {id},\n"));
        }
        out.push_str("};\n\n");
    }
    wire(page_ids, &mut out);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ids(v: &[&str]) -> Vec<String> {
        v.iter().map(|s| s.to_string()).collect()
    }

    /// The `pub mod union { ... }` block as a structure, not as a substring.
    ///
    /// `contains` on a prefix of the block proved neither that the block is
    /// CLOSED nor that nothing was attached to it. Two one-line mutations of
    /// the emitter passed against the old assertion: deleting the final
    /// `out.push_str("}\n")` (leaving the module unclosed, so the per-revision
    /// `pub mod v3_0;` declarations that follow are swallowed into it), and
    /// inserting `#[cfg(any())]` ahead of the block (compiling it out, so
    /// `crate::generated::union::CmisLowerMemory` — which openxcvr-cmis
    /// imports — ceases to exist). Return the body and the preceding line so
    /// both are assertable.
    struct UnionBlock {
        /// Non-empty lines of the block body, trimmed.
        items: Vec<String>,
        /// Every line attached to `pub mod union {` from above: the
        /// contiguous run of doc-comment, attribute and blank lines directly
        /// preceding it, trimmed, nearest first. Attributes apply across an
        /// intervening doc comment, so looking at only the line immediately
        /// above missed `#[cfg(any())]` placed above the emitter's own
        /// three-line `///` block -- which elides the module for real
        /// (rustc: E0433, `use of unresolved module union`) while the check
        /// saw a doc line and passed.
        attached: Vec<String>,
    }

    fn union_block(out: &str) -> UnionBlock {
        let lines: Vec<&str> = out.lines().collect();
        // Column 0 only: an indented match is nested inside another module,
        // which moves the sanctioned path.
        let starts: Vec<usize> = lines
            .iter()
            .enumerate()
            .filter(|(_, l)| **l == "pub mod union {")
            .map(|(i, _)| i)
            .collect();
        assert_eq!(
            starts.len(),
            1,
            "expected exactly one top-level `pub mod union {{`, found {}",
            starts.len()
        );
        let start = starts[0];

        // Brace-match forward so an unclosed block is a failure, not a pass.
        let mut depth = 0usize;
        let mut end = None;
        for (i, l) in lines.iter().enumerate().skip(start) {
            depth += l.matches('{').count();
            depth -= l.matches('}').count();
            if depth == 0 {
                end = Some(i);
                break;
            }
        }
        let end = end.expect("`pub mod union {` is never closed");

        UnionBlock {
            items: lines[start + 1..end]
                .iter()
                .map(|l| l.trim().to_string())
                .filter(|l| !l.is_empty())
                .collect(),
            attached: lines[..start]
                .iter()
                .rev()
                .map(|l| l.trim())
                .take_while(|l| l.is_empty() || l.starts_with("///") || l.starts_with("#["))
                .map(|l| l.to_string())
                .collect(),
        }
    }

    #[test]
    fn mod_rs_wires_enums_pages_and_revs() {
        let out = emit_mod_rs(
            "cmis",
            &ids(&["CmisModuleState"]),
            &ids(&["CmisLowerMemory"]),
            &ids(&["CmisLowerMemory"]),
            &[Rev::V3_0, Rev::V5_3],
            &[],
        );
        assert!(out.starts_with(HEADER));
        assert!(out.contains("tools/regen-rust.sh cmis"));
        assert!(out.contains("#[path = \"CmisModuleState.rs\"]\npub mod cmis_module_state;\npub use cmis_module_state::*;"));
        assert!(out.contains("#[path = \"CmisLowerMemory.rs\"]\nmod cmis_lower_memory;"));
        // The backing module must NOT be public: a public one is an unmarked
        // bypass around the union namespace (see declare()).
        assert!(!out.contains("pub mod cmis_lower_memory;"));
        // A versioned page must NOT be glob re-exported at the top level.
        assert!(!out.contains("pub use cmis_lower_memory::*;"));
        // ...and the re-export must be INSIDE it, in a block that is at the
        // top level, CLOSED, carries no attribute, and re-exports every
        // versioned page and nothing else. See union_block().
        let ub = union_block(&out);
        assert_eq!(ub.items, vec!["pub use super::cmis_lower_memory::*;"]);
        let attrs: Vec<&String> = ub.attached.iter().filter(|l| l.starts_with('#')).collect();
        assert!(
            attrs.is_empty(),
            "an attribute is attached to `pub mod union`: {:?} — \
             `#[cfg(any())]` would compile the only sanctioned path away. \
             It applies across the doc comment between them, so its distance \
             from the `pub mod` line is not what makes it harmless.",
            attrs
        );
        assert!(out.contains("pub mod v3_0;\npub mod v5_3;\n"));
        assert!(out.contains("pub mod catalog;\n"));
    }

    #[test]
    fn mod_rs_declares_fsm_only_when_machines_were_collected() {
        let with = emit_mod_rs(
            "cmis",
            &[],
            &[],
            &[],
            &[],
            &ids(&["CmisModuleStateMachine"]),
        );
        assert!(with.contains("pub mod fsm;"));
        let without = emit_mod_rs("sff-8636", &[], &[], &[], &[], &[]);
        assert!(!without.contains("pub mod fsm;"));
    }

    #[test]
    fn mod_rs_without_versioned_pages_declares_no_rev_dirs() {
        let out = emit_mod_rs(
            "sff-8636",
            &ids(&["Sff8024Identifier"]),
            &ids(&["Sff8636LowerMemory"]),
            &[],
            &[],
            &[],
        );
        assert!(!out.contains("pub mod v"));
        assert!(!out.contains("Per-revision"));
        // With no versioned page there is no union view, and the page keeps
        // its flat glob re-export.
        assert!(!out.contains("pub mod union {"));
        assert!(out.contains("pub use sff8636_lower_memory::*;"));
        assert!(out.contains("pub mod catalog;\n"));
    }

    #[test]
    fn rev_mod_rs_reexports_enums_and_wires_pages() {
        let out = emit_rev_mod_rs(
            "cmis",
            Rev::V4_0,
            &ids(&["CmisModuleState", "Sff8024Identifier"]),
            &ids(&["CmisPage01hAdvertising"]),
        );
        assert!(out.contains("CMIS 4.0"));
        assert!(out.contains("pub use super::{\n    CmisModuleState,\n    Sff8024Identifier,\n};"));
        assert!(out.contains(
            "#[path = \"CmisPage01hAdvertising.rs\"]\npub mod cmis_page01h_advertising;"
        ));
    }
}
