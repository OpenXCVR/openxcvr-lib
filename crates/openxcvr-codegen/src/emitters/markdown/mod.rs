//! Markdown reference emitter.
//!
//! Renders the documentation tree under `docs/reference/` from the same IR
//! and the same revision resolver (`ir::version`) that drive the Rust and
//! binding emitters. There is deliberately no second schema-semantics engine
//! here: everything shown is either read straight off the parsed IR or
//! explicitly marked `not recorded`.
//!
//! Tree layout (one file per schema, plus per-spec and top-level indexes):
//!
//! ```text
//! docs/reference/index.md
//! docs/reference/<spec>/index.md
//! docs/reference/<spec>/pages/<snake_id>.md
//! docs/reference/<spec>/enums/<snake_id>.md
//! ```
//!
//! The top-level index accumulates across separate `--spec` runs by scanning
//! the output directory (the same accumulation pattern as the C umbrella
//! header), so `tools/regen-markdown.sh` can invoke the generator once per
//! spec.

pub mod enums;
pub mod index;
pub mod pages;

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use crate::ir::enums::EnumSchema;
use crate::ir::pages::PageSchema;

/// Stamp every generated file carries. No timestamps — output must be
/// byte-identical across regenerations.
pub(crate) const GENERATED_BY: &str =
    "<!-- Generated by openxcvr-codegen --lang markdown. DO NOT EDIT. -->";

/// End a generated document with exactly one newline (git whitespace-clean).
pub(crate) fn finish_doc(mut text: String) -> String {
    while text.ends_with('\n') {
        text.pop();
    }
    text.push('\n');
    text
}

/// Escape a plain-text table cell: pipes would break the table, newlines
/// cannot appear in a cell, and angle brackets would be eaten as raw HTML
/// by Markdown renderers.
pub(crate) fn md_text(s: &str) -> String {
    s.replace('|', "\\|")
        .replace(['\r', '\n'], " ")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// Escape a value rendered inside a code span. HTML entities are NOT
/// interpreted inside code spans, so angle brackets stay literal; only the
/// table-breaking characters are escaped.
pub(crate) fn md_code(s: &str) -> String {
    s.replace('|', "\\|").replace(['\r', '\n'], " ")
}

/// Render a raw YAML scalar for inline documentation text.
pub(crate) fn scalar(v: &serde_norway::Value) -> String {
    if let Some(s) = v.as_str() {
        return s.to_string();
    }
    if let Some(b) = v.as_bool() {
        return b.to_string();
    }
    if let Some(n) = v.as_u64() {
        return n.to_string();
    }
    if let Some(n) = v.as_i64() {
        return n.to_string();
    }
    if let Some(f) = v.as_f64() {
        return format!("{f}");
    }
    format!("{v:?}")
}

/// Render a YAML sequence of scalars (`[141, 142]` → `141, 142`).
pub(crate) fn scalar_seq(v: &serde_norway::Value) -> Option<String> {
    let seq = v.as_sequence()?;
    Some(seq.iter().map(scalar).collect::<Vec<_>>().join(", "))
}

/// Compact citation of a provenance block (a mapping of spec references or a
/// plain string). Every recorded key is shown verbatim — nothing is inferred.
pub(crate) fn cite(value: Option<&serde_norway::Value>) -> String {
    let Some(value) = value else {
        return "not recorded".to_string();
    };
    if let Some(s) = value.as_str() {
        return md_text(s);
    }
    let Some(map) = value.as_mapping() else {
        return md_text(&format!("{value:?}"));
    };
    let mut parts: Vec<String> = Vec::new();
    for (key, val) in map {
        let key = scalar(key);
        // Any key may record a list of references (e.g. `pdf_page: [83]`);
        // render recorded sequences as comma-joined scalars, never as a
        // raw debug dump.
        let rendered = if val.is_sequence() {
            scalar_seq(val).unwrap_or_else(|| scalar(val))
        } else {
            scalar(val)
        };
        parts.push(format!("{key}: {rendered}"));
    }
    if parts.is_empty() {
        return "not recorded".to_string();
    }
    md_text(&parts.join(" · "))
}

/// Hex rendering of an enum value, matching the `0x..` spelling the schemas
/// use (`0x0`, `0x27`, `0x27..0x7f`).
pub(crate) fn value_hex(v: u64) -> String {
    format!("0x{v:02X}")
}

/// The spec directory a loaded schema belongs to (the top-level directory
/// under the schemas root that owns the file). Schemas pulled in through an
/// index `imports:` (e.g. sff-8024 enums under `--spec cmis`) keep their own
/// spec directory, so the docs tree mirrors schema ownership, not the run.
/// The rule itself is owned by [`crate::presence::namespace_of`], shared
/// with per-namespace presence validation so the two can never drift.
fn spec_of(schemas_root: &Path, path: &Path, spec_filter: Option<&str>) -> String {
    crate::presence::namespace_of(schemas_root, path)
        .unwrap_or_else(|| spec_filter.unwrap_or("ungrouped").to_string())
}

/// Path of a schema relative to the schemas root, for the generated-file
/// header (`schemas/cmis/lower-memory.yaml`).
fn source_rel(schemas_root: &Path, path: &Path) -> String {
    // Match the loader's lexical normalization before taking the relative path.
    let root = crate::parser::index::normalize_path(schemas_root);
    let path = crate::parser::index::normalize_path(path);
    path.strip_prefix(&root)
        .map(|p| p.display().to_string())
        .unwrap_or_else(|_| path.display().to_string())
        .replace(std::path::MAIN_SEPARATOR, "/")
}

/// Loaded `(source path, schema)` pairs, as the driver passes them in.
pub type EnumPairs<'a> = &'a [(PathBuf, EnumSchema)];
pub type PagePairs<'a> = &'a [(PathBuf, PageSchema)];

/// Emit the reference tree for the already-validated schemas loaded in this run.
/// Group by owning spec directory and accumulate the top-level index across
/// separate `--spec` runs. No timestamps or machine-specific paths are emitted.
pub fn emit_tree(
    schemas_root: &Path,
    spec_filter: Option<&str>,
    out_root: &Path,
    enums: EnumPairs<'_>,
    pages: PagePairs<'_>,
) -> anyhow::Result<()> {
    type SpecGroup<'a> = (
        Vec<&'a (PathBuf, EnumSchema)>,
        Vec<&'a (PathBuf, PageSchema)>,
    );
    let mut groups: BTreeMap<String, SpecGroup<'_>> = BTreeMap::new();
    for pair in enums {
        groups
            .entry(spec_of(schemas_root, &pair.0, spec_filter))
            .or_default()
            .0
            .push(pair);
    }
    for pair in pages {
        groups
            .entry(spec_of(schemas_root, &pair.0, spec_filter))
            .or_default()
            .1
            .push(pair);
    }

    for (spec, (enums, pages)) in &groups {
        let spec_dir = out_root.join(spec);
        let pages_dir = spec_dir.join("pages");
        let enums_dir = spec_dir.join("enums");
        if !pages.is_empty() {
            std::fs::create_dir_all(&pages_dir)?;
        }
        if !enums.is_empty() {
            std::fs::create_dir_all(&enums_dir)?;
        }

        // Sorted, collision-checked output stems: two schemas in one spec
        // whose ids collapse to the same snake-case stem would silently
        // overwrite each other — refuse that loudly.
        let mut seen: std::collections::BTreeSet<String> = Default::default();
        for (path, schema) in pages.iter() {
            let stem = pages::page_file_stem(schema);
            anyhow::ensure!(
                seen.insert(format!("pages/{stem}")),
                "page id {:?} collides with another page in spec {:?} (stem {stem})",
                schema.id,
                spec
            );
            std::fs::write(
                pages_dir.join(format!("{stem}.md")),
                pages::emit_page_doc(&source_rel(schemas_root, path), schema),
            )?;
        }
        seen.clear();
        for (path, schema) in enums.iter() {
            let stem = enums::enum_file_stem(schema);
            anyhow::ensure!(
                seen.insert(format!("enums/{stem}")),
                "enum id {:?} collides with another enum in spec {:?} (stem {stem})",
                schema.id,
                spec
            );
            std::fs::write(
                enums_dir.join(format!("{stem}.md")),
                enums::emit_enum_doc(&source_rel(schemas_root, path), schema),
            )?;
        }

        let body = index::emit_spec_index(
            schemas_root,
            spec,
            spec_filter,
            enums.iter().map(|(p, s)| (p.as_path(), s)).collect(),
            pages.iter().map(|(p, s)| (p.as_path(), s)).collect(),
        )?;
        std::fs::write(spec_dir.join("index.md"), body)?;
    }

    let top = index::emit_top_index(schemas_root, out_root)?;
    std::fs::create_dir_all(out_root)?;
    std::fs::write(out_root.join("index.md"), top)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn md_text_escapes_table_and_html_breakers() {
        assert_eq!(md_text("a|b"), "a\\|b");
        assert_eq!(md_text("a\nb"), "a b");
        assert_eq!(md_text("<lane>"), "&lt;lane&gt;");
    }

    #[test]
    fn md_code_keeps_angle_brackets_literal() {
        assert_eq!(md_code("a|b"), "a\\|b");
        assert_eq!(md_code("<lane>"), "<lane>");
    }

    #[test]
    fn cite_renders_mapping_keys_verbatim() {
        let v = serde_norway::from_str::<serde_norway::Value>(
            "section: \"§ 8.2.1\"\npdf_pages: [141, 142]",
        )
        .unwrap();
        let out = cite(Some(&v));
        assert_eq!(out, "section: § 8.2.1 · pdf_pages: 141, 142");
    }

    #[test]
    fn cite_none_is_not_recorded() {
        assert_eq!(cite(None), "not recorded");
    }
}
