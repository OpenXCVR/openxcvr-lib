use crate::media_interface::MediaInterfacePlan;

/// Emit the CMIS media-interface resolver as a Java static utility class.
/// Same semantics and fallback as the Go/TS resolvers: a known
/// `(media_type, code)` pair maps to its name, everything else to `null`.
pub fn emit_media_interface(plan: &MediaInterfacePlan) -> String {
    let mut out = String::new();
    out.push_str("// Generated by openxcvr-codegen. DO NOT EDIT.\n");
    out.push_str("package com.openxcvr.generated;\n\n");
    out.push_str("public final class CmisMediaInterface {\n\n");
    out.push_str("    private CmisMediaInterface() {}\n\n");
    out.push_str("    public static String name(int mediaType, int code) {\n");
    out.push_str("        if (mediaType < 0 || mediaType > 255 || code < 0 || code > 255) {\n");
    out.push_str("            return null;\n        }\n");
    out.push_str("        switch (mediaType) {\n");

    for (mt, _enum_id, entries) in &plan.tables {
        out.push_str(&format!("            case 0x{mt:02x}:\n"));
        for (lo, hi, name) in entries {
            if lo == hi {
                out.push_str(&format!(
                    "                if (code == 0x{lo:02x}) return \"{name}\";\n"
                ));
            } else {
                out.push_str(&format!(
                    "                if (code >= 0x{lo:02x} && code <= 0x{hi:02x}) return \"{name}\";\n"
                ));
            }
        }
        out.push_str("                return null;\n");
    }

    out.push_str("            default: return null;\n");
    out.push_str("        }\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn plan() -> MediaInterfacePlan {
        MediaInterfacePlan {
            tables: vec![
                (
                    0x02,
                    "Sff8024SmfMediaInterface".to_string(),
                    vec![
                        (0x01, 0x01, "base_10g_lw".to_string()),
                        (0xC0, 0xEF, "vendor_specific".to_string()),
                    ],
                ),
                (
                    0x06,
                    "UnsupportedTable".to_string(),
                    vec![(0x00, 0x00, "undefined".to_string())],
                ),
            ],
        }
    }

    #[test]
    fn emits_prelude_bounds_gate_and_class_shell() {
        let out = emit_media_interface(&plan());
        assert!(
            out.starts_with("// Generated by openxcvr-codegen. DO NOT EDIT.\n"),
            "{out}"
        );
        assert!(out.contains("package com.openxcvr.generated;"), "{out}");
        assert!(
            out.contains("public final class CmisMediaInterface {"),
            "{out}"
        );
        assert!(out.contains("private CmisMediaInterface() {}"), "{out}");
        assert!(
            out.contains("public static String name(int mediaType, int code)"),
            "{out}"
        );
        assert!(
            out.contains("if (mediaType < 0 || mediaType > 255 || code < 0 || code > 255) {"),
            "{out}"
        );
    }

    #[test]
    fn emits_single_and_range_arms_with_null_fallbacks() {
        let out = emit_media_interface(&plan());
        assert!(
            out.contains("case 0x02:\n                if (code == 0x01) return \"base_10g_lw\";"),
            "{out}"
        );
        assert!(
            out.contains("if (code >= 0xc0 && code <= 0xef) return \"vendor_specific\";"),
            "{out}"
        );
        // Per-table fallback after each table's arms, and the default arm for
        // unknown media types.
        assert!(
            out.matches("                return null;\n").count() >= 2,
            "{out}"
        );
        assert!(out.contains("            default: return null;\n"), "{out}");
    }
}
