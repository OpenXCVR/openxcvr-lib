use crate::ir::enums::{EntryValue, EnumSchema};
use crate::ir::naming::{JavaNaming, NamingPolicy};
use std::collections::HashSet;

/// Revision-bound name projection block, emitted only when the schema's
/// entries carry `since`/`until` metadata (see [`crate::emitters::enum_projection_rows`]).
/// Nested in the enum so the public surface stays one type: a SAM
/// `Projection` interface, a `forRevision(int)` factory returning `null` for
/// unknown revision bytes, and private per-revision label methods. The block
/// starts with `\n` and carries no trailing newline so unannotated enums
/// stay byte-identical.
fn projection_code(schema: &EnumSchema) -> String {
    let Some(rows) = crate::emitters::enum_projection_rows(schema) else {
        return String::new();
    };
    let pascal = JavaNaming.type_name(&schema.id);
    let mut out = String::new();
    out.push_str("\n    @FunctionalInterface\n");
    out.push_str("    public interface Projection {\n");
    out.push_str("        String label(int raw);\n");
    out.push_str("    }\n\n");
    let rev_byte = crate::emitters::rev_byte_param_camel(schema);
    out.push_str(&format!(
        "    public static {pascal}.Projection forRevision(int {rev_byte}) {{\n"
    ));
    out.push_str(&format!("        switch ({rev_byte}) {{\n"));
    for (rev, _) in &rows {
        out.push_str(&format!(
            "            case {:#04x}: return {pascal}::projectionV{};\n",
            rev.family_rev_byte(),
            rev.dirname()
        ));
    }
    out.push_str("            default: return null;\n");
    out.push_str("        }\n");
    out.push_str("    }\n");
    for (rev, entries) in &rows {
        out.push_str(&format!(
            "\n    private static String projectionV{}(int raw) {{\n",
            rev.dirname()
        ));
        out.push_str("        switch (raw) {\n");
        for (value, name) in entries {
            out.push_str(&format!(
                "            case {value:#04x}: return \"{name}\";\n"
            ));
        }
        out.push_str("            default: return null;\n");
        out.push_str("        }\n");
        out.push_str("    }\n");
    }
    out
}

/// Emit a Java `enum` with SCREAMING_SNAKE constants, an `int value`
/// field, and a static `label(int)` lookup.
pub fn emit_enum(schema: &EnumSchema) -> String {
    let type_name = JavaNaming.type_name(&schema.id);

    let singles: Vec<(&str, u64)> = schema
        .entries
        .iter()
        .filter_map(|e| match &e.value {
            EntryValue::Single(v) => Some((e.name.as_str(), *v)),
            EntryValue::Range { .. } => None,
        })
        .collect();

    let mut consts = String::new();
    let mut labels = String::new();
    let mut used: HashSet<String> = HashSet::new();
    for (i, (name, v)) in singles.iter().enumerate() {
        let mut variant = JavaNaming.enum_variant(name);
        if !used.insert(variant.clone()) {
            variant = format!("{variant}_VALUE_{v:02X}");
            while !used.insert(variant.clone()) {
                variant.push('_');
            }
        }
        let sep = if i + 1 == singles.len() { ";" } else { "," };
        consts.push_str(&format!("    {variant}(0x{v:02X}){sep}\n"));
        labels.push_str(&format!("            case 0x{v:02X}: return {name:?};\n"));
    }
    if consts.is_empty() {
        // Range-only enum: no constants, just the `;` terminator.
        consts.push_str("    ;\n");
    }

    format!(
        "// Generated by openxcvr-codegen. DO NOT EDIT.\n\
         package com.openxcvr.generated;\n\n\
         public enum {type_name} {{\n{consts}\n\
         \x20\x20\x20\x20public final int value;\n\
         \x20\x20\x20\x20{type_name}(int value) {{ this.value = value; }}\n\n\
         \x20\x20\x20\x20public static String label(int v) {{\n\
         \x20\x20\x20\x20\x20\x20\x20\x20switch (v) {{\n{labels}\
         \x20\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20default: return \"unknown\";\n\
         \x20\x20\x20\x20\x20\x20\x20\x20}}\n\
         \x20\x20\x20\x20}}\n{}}}\n",
        projection_code(schema)
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::enums::{EntryValue, EnumEntry, EnumSchema};

    fn entry(name: &str, v: u64) -> EnumEntry {
        EnumEntry {
            name: name.to_string(),
            value: EntryValue::Single(v),
            description: None,
            aliases: vec![],
            tags: vec![],
            signaling: None,
            reach: None,
            bit_rate_gbps: None,
            vendor_specific: None,
            since: None,
            until: None,
            changed_in: None,
            renamed_from: None,
            aliased_to: None,
            provenance: None,
        }
    }

    fn schema() -> EnumSchema {
        EnumSchema {
            spec: None,
            provenance: None,
            description: None,
            schema: "openxcvr.enum.v2".to_string(),
            kind: "enum".to_string(),
            id: "CmisModuleState".to_string(),
            title: "Module State".to_string(),
            entry_includes: vec![],
            entries: vec![entry("module_low_pwr", 0x01), entry("module_ready", 0x03)],
        }
    }

    #[test]
    fn emits_java_enum() {
        let out = emit_enum(&schema());
        assert!(out.contains("public enum CmisModuleState {"), "{out}");
        assert!(out.contains("MODULE_LOW_PWR(0x01),"), "{out}");
        assert!(out.contains("MODULE_READY(0x03);"), "{out}");
        assert!(out.contains("public final int value;"), "{out}");
        assert!(out.contains("case 0x03: return \"module_ready\";"), "{out}");
        assert!(out.contains("package com.openxcvr.generated;"), "{out}");
    }

    #[test]
    fn revision_projection_is_additive_and_domain_bound() {
        let schema = crate::emitters::test_support::validated_dpsm_schema();
        let out = emit_enum(&schema);

        // Additive: the flat surface is intact.
        assert!(
            out.contains("public enum CmisDataPathState {"),
            "flat enum survives\n---\n{out}"
        );
        assert!(
            out.contains("DP_TX_TURN_ON(0x05),"),
            "flat constant survives\n---\n{out}"
        );
        assert!(
            out.contains("public static String label(int v)"),
            "label(int) survives\n---\n{out}"
        );

        // Exact public interface.
        assert!(
            out.contains("@FunctionalInterface"),
            "projection SAM is a functional interface\n---\n{out}"
        );
        assert!(
            out.contains("public interface Projection {"),
            "projection interface\n---\n{out}"
        );
        assert!(
            out.contains("String label(int raw);"),
            "projection method\n---\n{out}"
        );
        assert!(
            out.contains(
                "public static CmisDataPathState.Projection forRevision(int cmisRevByte) {"
            ),
            "factory signature\n---\n{out}"
        );

        // Domain-bound dispatch: exactly the six packed-BCD catalog bytes.
        let factory = out
            .split("public static CmisDataPathState.Projection forRevision")
            .nth(1)
            .unwrap()
            .split("private static String projectionV3_0")
            .next()
            .unwrap();
        for (byte, rev) in [
            (0x30u8, "V3_0"),
            (0x40, "V4_0"),
            (0x50, "V5_0"),
            (0x51, "V5_1"),
            (0x52, "V5_2"),
            (0x53, "V5_3"),
            (0x54, "V5_4"),
        ] {
            assert!(
                factory.contains(&format!(
                    "case {byte:#04x}: return CmisDataPathState::projection{rev};"
                )),
                "catalog byte {byte:#04x} binds its projection\n---\n{factory}"
            );
        }
        assert!(
            factory.contains("default: return null;"),
            "refusal branch\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x55"),
            "5.5 is not a context\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x31"),
            "3.1 is not a context\n---\n{factory}"
        );

        // since/until filtering: 3.0 lacks the 4.0 names, keeps 0–4;
        // every 4.0+ projection has all eight names with canonical casing.
        let v3_0 = out
            .split("private static String projectionV3_0")
            .nth(1)
            .unwrap()
            .split("private static String projection")
            .next()
            .unwrap();
        assert!(
            v3_0.contains("case 0x04: return \"DpActivated\";"),
            "unannotated entry present at 3.0\n---\n{v3_0}"
        );
        assert!(
            !v3_0.contains("DpTxTurnOn"),
            "since 4.0 entry absent at 3.0\n---\n{v3_0}"
        );
        for rev in ["V4_0", "V5_0", "V5_1", "V5_2", "V5_3"] {
            let body = out
                .split(&format!("private static String projection{rev}"))
                .nth(1)
                .unwrap();
            for (value, name) in [
                (0x00u8, "Reserved0"),
                (0x01, "DpDeactivated"),
                (0x02, "DpInit"),
                (0x03, "DpDeinit"),
                (0x04, "DpActivated"),
                (0x05, "DpTxTurnOn"),
                (0x06, "DpTxTurnOff"),
                (0x07, "DpInitialized"),
            ] {
                assert!(
                    body.contains(&format!("case {value:#04x}: return \"{name}\";")),
                    "{rev} arm {value:#04x}\n---\n{body}"
                );
            }
            assert!(
                body.contains("default: return null;"),
                "{rev} refusal arm\n---\n{body}"
            );
        }

        // No range arm: reserved 8..0xf raws stay unnamed.
        assert!(
            !out.contains("case 0x08:"),
            "range raws unnamed\n---\n{out}"
        );
    }

    #[test]
    fn unannotated_enum_emission_is_unchanged() {
        let schema = crate::emitters::test_support::validated_unannotated_schema();
        let out = emit_enum(&schema);
        assert!(
            !out.contains("Projection"),
            "no projection items without entry metadata\n---\n{out}"
        );
        assert!(
            !out.contains("forRevision"),
            "no revision factory without entry metadata\n---\n{out}"
        );
        assert!(out.contains("public enum CmisDataPathState {"));
        assert!(out.contains("public static String label(int v)"));
    }

    /// The range-only path must not silently drop an appended projection:
    /// a range-only schema whose entries carry metadata still emits the
    /// factory, with all-null callables (ranges never name).
    #[test]
    fn range_only_annotated_enum_still_emits_projection() {
        let schema = crate::emitters::test_support::validated_range_only_annotated_schema();
        let out = emit_enum(&schema);
        // Valid declaration with zero constants: the bare `;` terminator.
        assert!(
            out.contains("public enum CmisDataPathState {\n    ;\n"),
            "range-only keeps a compilable declaration\n---\n{out}"
        );
        assert!(
            out.contains("public interface Projection {"),
            "range-only path keeps the projection interface\n---\n{out}"
        );
        assert!(
            out.contains(
                "public static CmisDataPathState.Projection forRevision(int cmisRevByte) {"
            ),
            "range-only path keeps the factory\n---\n{out}"
        );
        assert!(
            out.contains("public static String label(int v)"),
            "flat lookup survives\n---\n{out}"
        );
        for rev in ["V3_0", "V4_0", "V5_0", "V5_1", "V5_2", "V5_3"] {
            let body = out
                .split(&format!("private static String projection{rev}(int raw)"))
                .nth(1)
                .unwrap();
            assert!(
                !body.contains("return \""),
                "range-only matches never name ({rev})\n---\n{body}"
            );
            assert!(
                body.contains("default: return null;"),
                "({rev}) still refuses every raw\n---\n{body}"
            );
        }
    }
}
