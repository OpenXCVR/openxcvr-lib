use crate::ir::enums::{EntryValue, EnumSchema};
use crate::ir::naming::{NamingPolicy, PhpNaming};
use std::collections::HashSet;

/// Revision-bound name projection methods, emitted inside the enum only when
/// the schema's entries carry `since`/`until` metadata (see
/// [`crate::emitters::enum_projection_rows`]). Bounds checks run before any match, so
/// out-of-range integers are refused — never masked/coerced into a byte.
fn projection_code(schema: &EnumSchema) -> String {
    let Some(rows) = crate::emitters::enum_projection_rows(schema) else {
        return String::new();
    };
    let rev_byte = crate::emitters::rev_byte_param_camel(schema);
    let mut out = String::new();
    out.push_str(&format!(
        "\n    public static function forRevision(int ${rev_byte}): ?\\Closure\n    {{\n"
    ));
    out.push_str(&format!(
        "        if (${rev_byte} < 0 || ${rev_byte} > 0xFF) {{\n            return null;\n        }}\n"
    ));
    out.push_str(&format!("        return match (${rev_byte}) {{\n"));
    for (rev, _) in &rows {
        out.push_str(&format!(
            "            {:#04x} => self::projectionV{}(...),\n",
            rev.family_rev_byte(),
            rev.dirname()
        ));
    }
    out.push_str("            default => null,\n        };\n    }\n");
    for (rev, entries) in &rows {
        out.push_str(&format!(
            "\n    private static function projectionV{}(int $raw): ?string\n    {{\n",
            rev.dirname()
        ));
        out.push_str(
            "        if ($raw < 0 || $raw > 0xFF) {\n            return null;\n        }\n",
        );
        out.push_str("        return match ($raw) {\n");
        for (value, name) in entries {
            out.push_str(&format!("            {value:#04x} => '{name}',\n"));
        }
        out.push_str("            default => null,\n        };\n    }\n");
    }
    out
}

pub fn emit_enum(schema: &EnumSchema) -> String {
    let type_name = &schema.id;
    let mut cases = String::new();
    let mut labels = String::new();
    let mut used_cases = HashSet::new();

    for entry in &schema.entries {
        if let EntryValue::Single(v) = &entry.value {
            let mut case_name = PhpNaming.enum_variant(&entry.name);
            if !used_cases.insert(case_name.clone()) {
                case_name = format!("{case_name}Value{v:02X}");
                while !used_cases.insert(case_name.clone()) {
                    case_name.push('_');
                }
            }
            cases.push_str(&format!("    case {case_name} = 0x{v:02X};\n"));
            labels.push_str(&format!(
                "            self::{case_name} => {:?},\n",
                entry.name
            ));
        }
        // Range entries are not representable as a single backed-enum case — skip
    }

    let mut out = String::new();
    out.push_str("<?php\n");
    out.push_str("// Generated by openxcvr-codegen. DO NOT EDIT.\n");
    out.push_str("declare(strict_types=1);\n");
    out.push_str("namespace Openxcvr\\Generated\\Enums;\n");
    out.push('\n');
    out.push_str(&format!("enum {type_name}: int\n"));
    out.push_str("{\n");
    out.push_str(&cases);
    out.push('\n');
    out.push_str("    public function label(): string\n");
    out.push_str("    {\n");
    out.push_str("        return match ($this) {\n");
    out.push_str(&labels);
    out.push_str("            default => 'unknown',\n");
    out.push_str("        };\n");
    out.push_str("    }\n");
    out.push_str(&projection_code(schema));
    out.push_str("}\n");
    out
}

