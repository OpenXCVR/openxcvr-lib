    #[test]
    fn test_emit_enum_backed() {
        let schema = make_schema();
        let out = emit_enum(&schema);
        assert!(
            out.contains("enum CmisModuleState: int"),
            "missing backed enum declaration\n---\n{out}"
        );
        assert!(
            out.contains("case ModuleReady = 0x03;"),
            "missing case\n---\n{out}"
        );
        assert!(
            !out.contains("Reserved6"),
            "range entries must be skipped\n---\n{out}"
        );
        assert!(
            out.contains("namespace Openxcvr\\Generated\\Enums;"),
            "missing namespace\n---\n{out}"
        );
        assert!(out.starts_with("<?php"), "missing PHP open tag\n---\n{out}");
        assert!(
            out.contains("declare(strict_types=1);"),
            "missing strict_types\n---\n{out}"
        );
    }

