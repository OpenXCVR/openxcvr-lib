    // ── Revision-bound name projections (Task 2) ──────────────────────────

    #[test]
    fn revision_projection_is_additive_and_domain_bound() {
        let schema = crate::emitters::test_support::validated_dpsm_schema();
        let out = emit_enum(&schema);

        // Additive: the flat backed enum is intact.
        assert!(
            out.contains("enum CmisDataPathState: int"),
            "flat enum survives\n---\n{out}"
        );
        assert!(
            out.contains("case DpTxTurnOn = 0x05;"),
            "flat case survives\n---\n{out}"
        );
        assert!(
            out.contains("public function label(): string"),
            "label() survives\n---\n{out}"
        );

        // Exact public interface.
        assert!(
            out.contains("public static function forRevision(int $cmisRevByte): ?\\Closure"),
            "factory signature\n---\n{out}"
        );

        // Bounds check refuses before any dispatch: out-of-range integers are
        // never masked/coerced into a known byte.
        let factory = out
            .split("public static function forRevision")
            .nth(1)
            .unwrap()
            .split("private static function projectionV3_0")
            .next()
            .unwrap();
        assert!(
            factory.contains(
                "if ($cmisRevByte < 0 || $cmisRevByte > 0xFF) {\n            return null;"
            ),
            "bounds refusal precedes dispatch\n---\n{factory}"
        );

        // Domain-bound dispatch: exactly the six packed-BCD catalog bytes.
        for (byte, rev) in [
            (0x30u8, "V3_0"),
            (0x40, "V4_0"),
            (0x50, "V5_0"),
            (0x51, "V5_1"),
            (0x52, "V5_2"),
            (0x53, "V5_3"),
            (0x54, "V5_4"),
        ] {
            assert!(
                factory.contains(&format!("{byte:#04x} => self::projection{rev}(...)")),
                "catalog byte {byte:#04x} binds its projection\n---\n{factory}"
            );
        }
        assert!(
            factory.contains("default => null,"),
            "refusal branch (null, no callable)\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x55"),
            "5.5 is not a context\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x31"),
            "3.1 is not a context\n---\n{factory}"
        );

        // since/until filtering: 3.0 lacks the 4.0 names, keeps 0–4; every
        // 4.0+ projection names all eight singles with canonical casing.
        let v3_0 = out
            .split("private static function projectionV3_0")
            .nth(1)
            .unwrap()
            .split("\n\n    private static function")
            .next()
            .unwrap();
        assert!(
            v3_0.contains("0x04 => 'DpActivated',"),
            "unannotated entry present at 3.0\n---\n{v3_0}"
        );
        assert!(
            !v3_0.contains("DpTxTurnOn"),
            "since 4.0 entry absent at 3.0\n---\n{v3_0}"
        );
        for rev in ["V4_0", "V5_0", "V5_1", "V5_2", "V5_3"] {
            let body = out
                .split(&format!("private static function projection{rev}"))
                .nth(1)
                .unwrap()
                .split("\n\n    private static function")
                .next()
                .unwrap();
            // Raw bounds refusal precedes the match: raw is never aliased.
            assert!(
                body.contains("if ($raw < 0 || $raw > 0xFF) {\n            return null;"),
                "{rev} raw bounds refusal\n---\n{body}"
            );
            for (value, name) in [
                (0x00u8, "Reserved0"),
                (0x01, "DpDeactivated"),
                (0x02, "DpInit"),
                (0x03, "DpDeinit"),
                (0x04, "DpActivated"),
                (0x05, "DpTxTurnOn"),
                (0x06, "DpTxTurnOff"),
                (0x07, "DpInitialized"),
            ] {
                assert!(
                    body.contains(&format!("{value:#04x} => '{name}',")),
                    "{rev} arm {value:#04x}\n---\n{body}"
                );
            }
            assert!(
                body.contains("default => null,"),
                "{rev} refusal arm (null for unnamed raw)\n---\n{body}"
            );
        }

        // No range arm: reserved 8..0xf raws stay unnamed.
        assert!(!out.contains("0x08 =>"), "range raws unnamed\n---\n{out}");
    }

