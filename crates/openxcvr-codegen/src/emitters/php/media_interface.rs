use crate::media_interface::MediaInterfacePlan;

pub fn emit_media_interface(plan: &MediaInterfacePlan) -> String {
    let mut out = String::new();
    out.push_str("<?php\n\n// Generated by openxcvr-codegen. DO NOT EDIT.\n\ndeclare(strict_types=1);\n\nnamespace Openxcvr\\Generated\\Enums;\n\n");
    out.push_str("final class CmisMediaInterface\n{\n");
    out.push_str("    public static function nameOf(int $mediaType, int $code): ?string\n    {\n");
    out.push_str("        if ($mediaType < 0 || $mediaType > 0xFF || $code < 0 || $code > 0xFF) {\n            return null;\n        }\n\n");
    out.push_str("        switch ($mediaType) {\n");

    for (mt, _enum_id, entries) in &plan.tables {
        out.push_str(&format!("            case 0x{mt:02X}:\n"));
        for (lo, hi, name) in entries {
            if lo == hi {
                out.push_str(&format!("                if ($code === 0x{lo:02X}) {{\n"));
                out.push_str(&format!("                    return '{name}';\n"));
                out.push_str("                }\n");
            } else {
                out.push_str(&format!(
                    "                if ($code >= 0x{lo:02X} && $code <= 0x{hi:02X}) {{\n"
                ));
                out.push_str(&format!("                    return '{name}';\n"));
                out.push_str("                }\n");
            }
        }
        out.push_str("                return null;\n");
    }

    out.push_str("            default:\n");
    out.push_str("                return null;\n");
    out.push_str("        }\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    out
}
