use crate::ir::enums::{EntryValue, EnumSchema};
use crate::ir::naming::{CSharpNaming, NamingPolicy};
use std::collections::HashSet;

/// Revision-bound name projection block, emitted only when the schema's
/// entries carry `since`/`until` metadata (see [`crate::emitters::enum_projection_rows`]).
/// A top-level `{Type}Projection` delegate mirrors the Go/TS projection
/// types, with the `ForRevision` factory on a `{Type}Projections` static class
/// (C# has no free functions). The block starts with `\n` and carries no
/// trailing newline so unannotated enums stay byte-identical.
fn projection_code(schema: &EnumSchema) -> String {
    let Some(rows) = crate::emitters::enum_projection_rows(schema) else {
        return String::new();
    };
    let pascal = CSharpNaming.type_name(&schema.id);
    let mut out = String::new();
    out.push_str(&format!(
        "\n    public delegate string? {pascal}Projection(int raw);\n\n"
    ));
    out.push_str(&format!(
        "    public static class {pascal}Projections\n    {{\n"
    ));
    let rev_byte = crate::emitters::rev_byte_param_camel(schema);
    out.push_str(&format!(
        "        public static {pascal}Projection? ForRevision(int {rev_byte})\n        {{\n"
    ));
    out.push_str(&format!(
        "            switch ({rev_byte})\n            {{\n"
    ));
    for (rev, _) in &rows {
        out.push_str(&format!(
            "                case {:#04x}: return ProjectionV{};\n",
            rev.family_rev_byte(),
            rev.dirname()
        ));
    }
    out.push_str("                default: return null;\n");
    out.push_str("            }\n");
    out.push_str("        }\n");
    for (rev, entries) in &rows {
        out.push_str(&format!(
            "\n        private static string? ProjectionV{}(int raw) => raw switch\n        {{\n",
            rev.dirname()
        ));
        for (value, name) in entries {
            out.push_str(&format!("            {value:#04x} => \"{name}\",\n"));
        }
        out.push_str("            _ => null,\n");
        out.push_str("        };\n");
    }
    out.push_str("    }\n");
    out
}

/// Emit a C# scoped `enum` (PascalCase members per) plus a static
/// `<Type>Labels.Label(int)` lookup using a switch expression.
pub fn emit_enum(schema: &EnumSchema) -> String {
    let type_name = CSharpNaming.type_name(&schema.id);

    let singles: Vec<(&str, u64)> = schema
        .entries
        .iter()
        .filter_map(|e| match &e.value {
            EntryValue::Single(v) => Some((e.name.as_str(), *v)),
            EntryValue::Range { .. } => None,
        })
        .collect();

    let mut members = String::new();
    let mut arms = String::new();
    let mut used: HashSet<String> = HashSet::new();
    for (name, v) in &singles {
        let mut variant = CSharpNaming.enum_variant(name);
        if !used.insert(variant.clone()) {
            variant = format!("{variant}Value{v:02X}");
            while !used.insert(variant.clone()) {
                variant.push('_');
            }
        }
        members.push_str(&format!("        {variant} = 0x{v:02X},\n"));
        arms.push_str(&format!("            0x{v:02X} => {name:?},\n"));
    }

    format!(
        "// Generated by openxcvr-codegen. DO NOT EDIT.\n\
         namespace OpenXcvr.Generated\n{{\n\
         \x20\x20\x20\x20public enum {type_name}\n    {{\n{members}    }}\n\n\
         \x20\x20\x20\x20public static class {type_name}Labels\n    {{\n\
         \x20\x20\x20\x20\x20\x20\x20\x20public static string Label(int v) => v switch\n        {{\n{arms}\
         \x20\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20\x20_ => \"unknown\",\n        }};\n    }}\n{}}}\n",
        projection_code(schema)
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::enums::{EntryValue, EnumEntry, EnumSchema};

    fn entry(name: &str, v: u64) -> EnumEntry {
        EnumEntry {
            name: name.to_string(),
            value: EntryValue::Single(v),
            description: None,
            aliases: vec![],
            tags: vec![],
            signaling: None,
            reach: None,
            bit_rate_gbps: None,
            vendor_specific: None,
            since: None,
            until: None,
            changed_in: None,
            renamed_from: None,
            aliased_to: None,
            provenance: None,
        }
    }

    fn schema() -> EnumSchema {
        EnumSchema {
            spec: None,
            provenance: None,
            description: None,
            schema: "openxcvr.enum.v2".to_string(),
            kind: "enum".to_string(),
            id: "CmisModuleState".to_string(),
            title: "Module State".to_string(),
            entry_includes: vec![],
            entries: vec![entry("module_low_pwr", 0x01), entry("module_ready", 0x03)],
        }
    }

    #[test]
    fn emits_csharp_enum() {
        let out = emit_enum(&schema());
        assert!(out.contains("namespace OpenXcvr.Generated"), "{out}");
        assert!(out.contains("public enum CmisModuleState"), "{out}");
        assert!(out.contains("ModuleLowPwr = 0x01,"), "{out}");
        assert!(out.contains("ModuleReady = 0x03,"), "{out}");
        assert!(
            out.contains("public static class CmisModuleStateLabels"),
            "{out}"
        );
        assert!(out.contains("0x03 => \"module_ready\","), "{out}");
    }

    #[test]
    fn revision_projection_is_additive_and_domain_bound() {
        let schema = crate::emitters::test_support::validated_dpsm_schema();
        let out = emit_enum(&schema);

        // Additive: the flat surface is intact.
        assert!(
            out.contains("public enum CmisDataPathState"),
            "flat enum survives\n---\n{out}"
        );
        assert!(
            out.contains("DpTxTurnOn = 0x05,"),
            "flat member survives\n---\n{out}"
        );
        assert!(
            out.contains("public static class CmisDataPathStateLabels"),
            "Labels class survives\n---\n{out}"
        );

        // Exact public interface.
        assert!(
            out.contains("public delegate string? CmisDataPathStateProjection(int raw);"),
            "projection delegate\n---\n{out}"
        );
        assert!(
            out.contains("public static class CmisDataPathStateProjections"),
            "projection holder class\n---\n{out}"
        );
        assert!(
            out.contains("public static CmisDataPathStateProjection? ForRevision(int cmisRevByte)"),
            "factory signature\n---\n{out}"
        );

        // Domain-bound dispatch: exactly the six packed-BCD catalog bytes.
        let factory = out
            .split("public static CmisDataPathStateProjection? ForRevision")
            .nth(1)
            .unwrap()
            .split("private static string? ProjectionV3_0")
            .next()
            .unwrap();
        for (byte, rev) in [
            (0x30u8, "V3_0"),
            (0x40, "V4_0"),
            (0x50, "V5_0"),
            (0x51, "V5_1"),
            (0x52, "V5_2"),
            (0x53, "V5_3"),
            (0x54, "V5_4"),
        ] {
            assert!(
                factory.contains(&format!("case {byte:#04x}: return Projection{rev};")),
                "catalog byte {byte:#04x} binds its projection\n---\n{factory}"
            );
        }
        assert!(
            factory.contains("default: return null;"),
            "refusal branch\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x55"),
            "5.5 is not a context\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x31"),
            "3.1 is not a context\n---\n{factory}"
        );

        // since/until filtering: 3.0 lacks the 4.0 names, keeps 0–4;
        // every 4.0+ projection has all eight names with canonical casing.
        let v3_0 = out
            .split("private static string? ProjectionV3_0")
            .nth(1)
            .unwrap()
            .split("private static string? Projection")
            .next()
            .unwrap();
        assert!(
            v3_0.contains("0x04 => \"DpActivated\","),
            "unannotated entry present at 3.0\n---\n{v3_0}"
        );
        assert!(
            !v3_0.contains("DpTxTurnOn"),
            "since 4.0 entry absent at 3.0\n---\n{v3_0}"
        );
        for rev in ["V4_0", "V5_0", "V5_1", "V5_2", "V5_3"] {
            let body = out
                .split(&format!("private static string? Projection{rev}"))
                .nth(1)
                .unwrap();
            for (value, name) in [
                (0x00u8, "Reserved0"),
                (0x01, "DpDeactivated"),
                (0x02, "DpInit"),
                (0x03, "DpDeinit"),
                (0x04, "DpActivated"),
                (0x05, "DpTxTurnOn"),
                (0x06, "DpTxTurnOff"),
                (0x07, "DpInitialized"),
            ] {
                assert!(
                    body.contains(&format!("{value:#04x} => \"{name}\",")),
                    "{rev} arm {value:#04x}\n---\n{body}"
                );
            }
            assert!(
                body.contains("_ => null,"),
                "{rev} refusal arm\n---\n{body}"
            );
        }

        // No range arm: reserved 8..0xf raws stay unnamed.
        assert!(!out.contains("0x08 =>"), "range raws unnamed\n---\n{out}");
    }

    #[test]
    fn unannotated_enum_emission_is_unchanged() {
        let schema = crate::emitters::test_support::validated_unannotated_schema();
        let out = emit_enum(&schema);
        assert!(
            !out.contains("Projection"),
            "no projection items without entry metadata\n---\n{out}"
        );
        assert!(
            !out.contains("ForRevision"),
            "no revision factory without entry metadata\n---\n{out}"
        );
        assert!(out.contains("public enum CmisDataPathState"));
        assert!(out.contains("public static class CmisDataPathStateLabels"));
    }

    /// The range-only path must not silently drop an appended projection:
    /// a range-only schema whose entries carry metadata still emits the
    /// factory, with all-null callables (ranges never name).
    #[test]
    fn range_only_annotated_enum_still_emits_projection() {
        let schema = crate::emitters::test_support::validated_range_only_annotated_schema();
        let out = emit_enum(&schema);
        // Valid declaration with zero members: an empty body compiles.
        assert!(
            out.contains("public enum CmisDataPathState\n    {\n    }"),
            "range-only keeps a compilable declaration\n---\n{out}"
        );
        assert!(
            out.contains("public delegate string? CmisDataPathStateProjection(int raw);"),
            "range-only path keeps the projection delegate\n---\n{out}"
        );
        assert!(
            out.contains("public static class CmisDataPathStateProjections"),
            "range-only path keeps the factory holder\n---\n{out}"
        );
        assert!(
            out.contains("public static CmisDataPathStateProjection? ForRevision(int cmisRevByte)"),
            "range-only path keeps the factory\n---\n{out}"
        );
        assert!(
            out.contains("public static class CmisDataPathStateLabels"),
            "flat lookup survives\n---\n{out}"
        );
        for rev in ["V3_0", "V4_0", "V5_0", "V5_1", "V5_2", "V5_3"] {
            let body = out
                .split(&format!("private static string? Projection{rev}(int raw)"))
                .nth(1)
                .unwrap();
            assert!(
                !body.contains("=> \""),
                "range-only matches never name ({rev})\n---\n{body}"
            );
            assert!(
                body.contains("_ => null,"),
                "({rev}) still refuses every raw\n---\n{body}"
            );
        }
    }
}
