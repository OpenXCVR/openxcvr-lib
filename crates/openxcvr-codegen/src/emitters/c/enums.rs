use crate::ir::enums::{EntryValue, EnumSchema};
use crate::ir::naming::{self, camel_to_snake, CNaming, NamingPolicy};

/// The C raw-value type for an enum's value magnitude.
fn raw_c_type(schema: &EnumSchema) -> &'static str {
    let max = schema
        .entries
        .iter()
        .filter_map(|e| e.value.as_single())
        .max()
        .unwrap_or(0);
    if max <= 0xFF {
        "uint8_t"
    } else if max <= 0xFFFF {
        "uint16_t"
    } else {
        "uint32_t"
    }
}

/// Revision-bound name projection block, emitted only when the schema's
/// entries carry `since`/`until` metadata (see [`crate::emitters::enum_projection_rows`]).
/// Everything is `static inline` with read-only string literals: no new
/// includes, no writable buffers, no file-scope data tables — the header
/// stays freestanding-compile clean when nothing calls it.
fn projection_code(schema: &EnumSchema) -> String {
    let Some(rows) = crate::emitters::enum_projection_rows(schema) else {
        return String::new();
    };
    let snake = camel_to_snake(&schema.id);
    let raw = raw_c_type(schema);
    let mut out = String::new();
    out.push_str(&format!(
        "\ntypedef const char *(*openxcvr_{snake}_projection)({raw} raw);\n"
    ));
    for (rev, entries) in &rows {
        out.push_str(&format!(
            "\nstatic inline const char *openxcvr_{snake}_projection_v{}({raw} raw)\n{{\n    switch (raw) {{\n",
            rev.dirname()
        ));
        for (value, name) in entries {
            out.push_str(&format!("    case {value:#04x}: return \"{name}\";\n"));
        }
        out.push_str("    default: return 0;\n    }\n}\n");
    }
    let rev_byte = crate::emitters::rev_byte_param(schema);
    out.push_str(&format!(
        "\nstatic inline openxcvr_{snake}_projection\nopenxcvr_{snake}_for_revision(uint8_t {rev_byte})\n{{\n    switch ({rev_byte}) {{\n"
    ));
    for (rev, _) in &rows {
        out.push_str(&format!(
            "    case {:#04x}: return openxcvr_{snake}_projection_v{};\n",
            rev.family_rev_byte(),
            rev.dirname()
        ));
    }
    out.push_str("    default: return 0;\n    }\n}\n");
    out
}

pub fn emit_enum(schema: &EnumSchema) -> String {
    let type_suffix = CNaming.type_name(&schema.id);
    let type_name = format!("openxcvr_{type_suffix}");
    let const_prefix = format!("OPENXCVR_{}", naming::screaming_snake(&schema.id));

    let mut variants = String::new();
    for entry in &schema.entries {
        if let EntryValue::Single(value) = &entry.value {
            variants.push_str(&format!(
                "    {const_prefix}_{} = 0x{value:02X},\n",
                CNaming.enum_variant(&entry.name)
            ));
        }
    }
    if variants.is_empty() {
        variants.push_str(&format!("    {const_prefix}_UNSPECIFIED = 0x00,\n"));
    }

    format!(
        concat!(
            "/* Generated by openxcvr-codegen. DO NOT EDIT. */\n",
            "#pragma once\n\n",
            "#include <stdint.h>\n\n",
            "typedef enum {type_name} {{\n",
            "{variants}",
            "}} {type_name};\n",
            "{projection}",
        ),
        type_name = type_name,
        variants = variants,
        projection = projection_code(schema),
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::enums::{EntryValue, EnumEntry, EnumSchema};

    fn make_schema() -> EnumSchema {
        EnumSchema {
            spec: None,
            provenance: None,
            description: None,
            schema: "openxcvr.enum.v2".to_string(),
            kind: "enum".to_string(),
            id: "CmisModuleState".to_string(),
            title: "Module State".to_string(),
            entry_includes: vec![],
            entries: vec![
                EnumEntry {
                    name: "module_ready".to_string(),
                    value: EntryValue::Single(0x03),
                    description: None,
                    aliases: vec![],
                    tags: vec![],
                    signaling: None,
                    reach: None,
                    bit_rate_gbps: None,
                    vendor_specific: None,
                    since: None,
                    until: None,
                    changed_in: None,
                    renamed_from: None,
                    aliased_to: None,
                    provenance: None,
                },
                EnumEntry {
                    name: "reserved_6_7".to_string(),
                    value: EntryValue::Range { start: 6, end: 7 },
                    description: None,
                    aliases: vec![],
                    tags: vec![],
                    signaling: None,
                    reach: None,
                    bit_rate_gbps: None,
                    vendor_specific: None,
                    since: None,
                    until: None,
                    changed_in: None,
                    renamed_from: None,
                    aliased_to: None,
                    provenance: None,
                },
            ],
        }
    }

    #[test]
    fn emits_c_enum_header() {
        let out = emit_enum(&make_schema());
        assert!(out.contains("#pragma once"), "missing pragma\n{out}");
        assert!(
            out.contains("typedef enum openxcvr_cmis_module_state"),
            "missing typedef\n{out}"
        );
        assert!(
            out.contains("OPENXCVR_CMIS_MODULE_STATE_MODULE_READY = 0x03"),
            "missing variant\n{out}"
        );
        assert!(
            !out.contains("RESERVED_6_7"),
            "range entry should be skipped\n{out}"
        );
    }

    #[test]
    fn emits_sentinel_for_empty_c_enum() {
        let mut schema = make_schema();
        schema.entries = vec![];
        let out = emit_enum(&schema);
        assert!(
            out.contains("OPENXCVR_CMIS_MODULE_STATE_UNSPECIFIED = 0x00"),
            "missing empty-enum sentinel\n{out}"
        );
    }

    // ── Revision-bound name projections (Task 2) ──────────────────────────

    #[test]
    fn revision_projection_is_additive_and_domain_bound() {
        let schema = crate::emitters::test_support::validated_dpsm_schema();
        let out = emit_enum(&schema);

        // Additive: the flat enum constants are intact.
        assert!(
            out.contains("typedef enum openxcvr_cmis_data_path_state"),
            "flat enum survives\n---\n{out}"
        );
        assert!(
            out.contains("OPENXCVR_CMIS_DATA_PATH_STATE_DP_TX_TURN_ON = 0x05,"),
            "flat constant survives\n---\n{out}"
        );

        // Exact public interface: pointer typedef + static inline factory.
        assert!(
            out.contains(
                "typedef const char *(*openxcvr_cmis_data_path_state_projection)(uint8_t raw);"
            ),
            "projection typedef\n---\n{out}"
        );
        assert!(
            out.contains("static inline openxcvr_cmis_data_path_state_projection"),
            "factory must be static inline\n---\n{out}"
        );
        assert!(
            out.contains("openxcvr_cmis_data_path_state_for_revision(uint8_t cmis_rev_byte)"),
            "factory name and parameter\n---\n{out}"
        );

        // Every generated function is static inline (header hygiene); no
        // include beyond the existing <stdint.h> and no file-scope tables.
        assert!(
            !out.contains("\nstatic const"),
            "no file-scope data tables\n---\n{out}"
        );
        let include_count = out.matches("#include").count();
        assert_eq!(
            include_count, 1,
            "exactly the existing <stdint.h> include\n---\n{out}"
        );
        let static_fns = out.matches("static inline const char *").count();
        assert_eq!(
            static_fns, 7,
            "seven per-revision projections, all static inline\n---\n{out}"
        );
        assert!(
            out.lines()
                .all(|l| !l.starts_with("static ") || l.starts_with("static inline")),
            "every generated function is static inline\n---\n{out}"
        );

        // Domain-bound dispatch: exactly the six packed-BCD catalog bytes.
        let factory = out
            .split("openxcvr_cmis_data_path_state_for_revision(uint8_t cmis_rev_byte)")
            .nth(1)
            .unwrap();
        for (byte, rev) in [
            (0x30u8, "v3_0"),
            (0x40, "v4_0"),
            (0x50, "v5_0"),
            (0x51, "v5_1"),
            (0x52, "v5_2"),
            (0x53, "v5_3"),
            (0x54, "v5_4"),
        ] {
            assert!(
                factory.contains(&format!(
                    "case {byte:#04x}: return openxcvr_cmis_data_path_state_projection_{rev};"
                )),
                "catalog byte {byte:#04x} binds its projection\n---\n{factory}"
            );
        }
        assert!(
            factory.contains("default: return 0;"),
            "refusal branch (NULL, no callable)\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x55"),
            "5.5 is not a context\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x31"),
            "3.1 is not a context\n---\n{factory}"
        );

        // since/until filtering: 3.0 lacks the 4.0 names, keeps 0–4; every
        // 4.0+ projection names all eight singles with canonical casing.
        let v3_0 = out
            .split("openxcvr_cmis_data_path_state_projection_v3_0(uint8_t raw)")
            .nth(1)
            .unwrap()
            .split("\n\nstatic inline")
            .next()
            .unwrap();
        assert!(
            v3_0.contains("case 0x04: return \"DpActivated\";"),
            "unannotated entry present at 3.0\n---\n{v3_0}"
        );
        assert!(
            !v3_0.contains("DpTxTurnOn"),
            "since 4.0 entry absent at 3.0\n---\n{v3_0}"
        );
        for rev in ["v4_0", "v5_0", "v5_1", "v5_2", "v5_3"] {
            let body = out
                .split(&format!(
                    "openxcvr_cmis_data_path_state_projection_{rev}(uint8_t raw)"
                ))
                .nth(1)
                .unwrap()
                .split("\n\nstatic inline")
                .next()
                .unwrap();
            for (value, name) in [
                (0x00u8, "Reserved0"),
                (0x01, "DpDeactivated"),
                (0x02, "DpInit"),
                (0x03, "DpDeinit"),
                (0x04, "DpActivated"),
                (0x05, "DpTxTurnOn"),
                (0x06, "DpTxTurnOff"),
                (0x07, "DpInitialized"),
            ] {
                assert!(
                    body.contains(&format!("case {value:#04x}: return \"{name}\";")),
                    "{rev} arm {value:#04x}\n---\n{body}"
                );
            }
            assert!(
                body.contains("default: return 0;"),
                "{rev} refusal arm (NULL for unnamed raw)\n---\n{body}"
            );
        }

        // No range arm: reserved 8..0xf raws stay unnamed.
        assert!(
            !out.contains("case 0x08:"),
            "range raws unnamed\n---\n{out}"
        );
    }

    #[test]
    fn unannotated_enum_emission_is_unchanged() {
        let schema = crate::emitters::test_support::validated_unannotated_schema();
        let out = emit_enum(&schema);
        assert!(
            !out.contains("projection") && !out.contains("for_revision"),
            "no projection items without entry metadata\n---\n{out}"
        );
        assert!(
            out.contains("typedef enum openxcvr_cmis_data_path_state"),
            "flat enum survives\n---\n{out}"
        );
    }
}
