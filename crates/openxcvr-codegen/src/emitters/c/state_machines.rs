    #[test]
    fn unreported_states_get_a_machine_space_enum_and_host_policy() {
        let yaml = "schema: openxcvr.state_machine.v2\n\
            kind: state_machine\n\
            id: TestMachine\n\
            state_enum: TestState\n\
            initial_state: Hidden\n\
            states:\n\
            \x20 - { name: Hidden, class: transient, reported: false, is_initial: true }\n\
            \x20 - { name: Off, enum_value: 0x1, class: stable }\n\
            \x20 - { name: On, enum_value: 0x2, class: terminal, is_terminal: true }\n\
            terminal_states:\n\
            \x20 - { state: On, exit: software_recovery }\n\
            host_policy:\n\
            \x20 poll_cadence:\n\
            \x20   value_ms: 50\n\
            \x20   provenance: { repo: kernel-module, file: power.c, lines: [79] }\n\
            transitions:\n\
            \x20 - id: hidden_to_off\n\
            \x20   from: Hidden\n\
            \x20   to: Off\n\
            \x20   trigger: { kind: internal }\n\
            \x20 - id: off_to_on\n\
            \x20   from: Off\n\
            \x20   to: On\n\
            \x20   trigger: { kind: register_write, register: lower.req, value: 1 }\n";
        let schema = parse_state_machine_schema(yaml).expect("machine parses");
        let enums = vec![enum_schema()];
        let header =
            emit_state_machine_c_header(&schema, &enums).expect("header emission succeeds");
        let source =
            emit_state_machine_c_source(&schema, &enums).expect("source emission succeeds");
        // The complete space enum: unreported and reported states together,
        // values equal to the state's index.
        assert!(header.contains("typedef enum openxcvr_test_state_space {"));
        assert!(header.contains("    OPENXCVR_TEST_STATE_SPACE_HIDDEN = 0,"));
        assert!(header.contains("    OPENXCVR_TEST_STATE_SPACE_OFF = 1,"));
        assert!(header.contains("    OPENXCVR_TEST_STATE_SPACE_ON = 2,"));
        assert!(header.contains("} openxcvr_test_state_space;"));
        // Tables run over space members: the initial state is unreported.
        assert!(source.contains(".initial = OPENXCVR_TEST_STATE_SPACE_HIDDEN"));
        assert!(
            source.contains(
                ".from = OPENXCVR_TEST_STATE_SPACE_HIDDEN, \
                 .to = OPENXCVR_TEST_STATE_SPACE_OFF"
            ),
            "unreported endpoints must emit space members:\n{source}"
        );
        // Reported states expose their registry value through the state
        // descriptor, fail closed (0) for unreported ones.
        assert!(source.contains(
            ".state = OPENXCVR_TEST_STATE_SPACE_OFF, .state_class = \
             OPENXCVR_FSM_STATE_CLASS_STABLE, .reported = true, .reported_value = 0x1"
        ));
        assert!(source.contains(
            ".state = OPENXCVR_TEST_STATE_SPACE_HIDDEN, .state_class = \
             OPENXCVR_FSM_STATE_CLASS_TRANSIENT, .reported = false, .reported_value = 0x0"
        ));
        // Host policy constants beside the timeout sources, apart from
        // standard timers; only the values the schema records.
        assert!(header
            .contains("#define OPENXCVR_TEST_MACHINE_HOST_POLICY_POLL_CADENCE_MS UINT64_C(50)"));
        assert!(!header.contains("HOST_POLICY_READINESS_BACKSTOP"));
        assert!(
            !source.contains("OPENXCVR_FSM_TIMEOUT_SOURCE_HOST_POLICY"),
            "no host-policy timeout is recorded, so none may appear as one"
        );
    }

    #[test]
