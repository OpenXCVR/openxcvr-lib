//! C emitter for `openxcvr.state_machine.v1/v2` schemas:
//! the C half of the internal behaviour tables
//! the kernel module may compile in.
//!
//! The Rust emitter (`crate::emitters::rust::state_machines`) emits
//! `FsmTable` values built from `openxcvr_core::fsm` descriptors; this
//! emitter mirrors the same schema into a self-contained pure-data C pair
//! per machine under `fsm/` of the C generated tree:
//!
//! - `fsm/behaviour_tables.h` — the shared descriptor structs
//!   (one `openxcvr_fsm_*` vocabulary mirroring `openxcvr_core::fsm`), so
//!   every machine's tables share one format. `openxcvr-lib` owns this
//!   table format; the kernel UAPI and ABI stay in the kernel module.
//! - `fsm/<machine>.h` / `fsm/<machine>.c` — one machine's header (state
//!   enum, host-policy constants, fail-closed revision factories) and
//!   source (per-revision pure-data tables). No code beyond the two
//!   factory lookups: no I/O, no clocks, no resident state, no functions
//!   the caller could mistake for execution.
//!
//! The schema is the single source of truth and every cross-reference is
//! validated at generation time exactly like the Rust emitter: reported
//! states resolve through the `openxcvr.enum.v2` registry the machine's
//! `state_enum:` names, and a machine/enum mismatch fails the run instead
//! of emitting a table that disagrees with the enum schema.
//!
//! Revision awareness is strict: tables are emitted only for the catalog
//! revisions the machine actually covers, and the emitted factories return
//! `NULL` for every other context — the C mirror of the Rust
//! `for_revision` fail-closed pattern. No assume-latest, no nearest-table
//! fallback.

use std::collections::{BTreeMap, BTreeSet};

