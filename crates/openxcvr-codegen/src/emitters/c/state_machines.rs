    #[test]
    fn timeout_into_state_absent_from_revision_fails_loud() {
        let yaml = "schema: openxcvr.state_machine.v2\n\
            kind: state_machine\n\
            id: TestMachine\n\
            state_enum: TestState\n\
            initial_state: Off\n\
            states:\n\
            \x20 - { name: Off, enum_value: 0x1, class: stable, is_initial: true }\n\
            \x20 - { name: On, enum_value: 0x2, class: terminal, is_terminal: true }\n\
            terminal_states:\n\
            \x20 - { state: On, exit: software_recovery }\n\
            transitions:\n\
            \x20 - id: off_to_on\n\
            \x20   from: Off\n\
            \x20   to: On\n\
            \x20   trigger: { kind: register_write, register: lower.req, value: 1 }\n";
        let schema = parse_state_machine_schema(yaml).expect("machine parses");
        let mut schema = schema;
        // The parser keeps a transition's endpoints in every revision of the
        // transition, so the inconsistent window is reached by mutating valid
        // IR past it (defense-in-depth, like the Rust emitter's own test):
        // On narrows to since 5.0 while Off's timeout expires into it for
        // every revision — the 3.0 table cannot reference it.
        schema.states[1].revs = crate::ir::state_machines::RevRange {
            since: Some(Rev::V5_0),
            until: None,
        };
        schema.states[0].timeouts = vec![StateTimeout {
            source: TimeoutSource::Standard {
                timer: "tTest".into(),
                duration: TimerDuration::FixedMs(100),
            },
            on_expiry: Some("On".into()),
            revs: crate::ir::state_machines::RevRange::ALL,
            provenance: None,
        }];
        let enums = vec![enum_schema()];
        let err = emit_state_machine_c_source(&schema, &enums)
            .expect_err("on_expiry destination must exist in the revision");
        assert!(
            err.to_string()
                .contains("revision windows are inconsistent"),
            "got: {err:#}"
        );
    }

