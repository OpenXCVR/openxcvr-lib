use crate::media_interface::MediaInterfacePlan;

pub fn emit_media_interface(plan: &MediaInterfacePlan) -> String {
    let mut out = String::new();
    out.push_str("/* Generated by openxcvr-codegen. DO NOT EDIT. */\n");
    out.push_str("#pragma once\n\n");
    out.push_str("#include <stddef.h>\n");
    out.push_str("#include <stdint.h>\n\n");
    out.push_str("static inline const char *openxcvr_cmis_media_interface_name(uint8_t media_type, uint8_t code)\n{\n");
    out.push_str("    switch (media_type) {\n");

    for (mt, _enum_id, entries) in &plan.tables {
        out.push_str(&format!("    case 0x{mt:02x}:\n"));
        for (lo, hi, name) in entries {
            if lo == hi {
                out.push_str(&format!(
                    "        if (code == 0x{lo:02x}) return \"{name}\";\n"
                ));
            } else if *lo == 0 && *hi == 0xff {
                out.push_str(&format!("        return \"{name}\";\n"));
            } else if *hi == 0xff {
                out.push_str(&format!(
                    "        if (code >= 0x{lo:02x}) return \"{name}\";\n"
                ));
            } else if *lo == 0 {
                out.push_str(&format!(
                    "        if (code <= 0x{hi:02x}) return \"{name}\";\n"
                ));
            } else {
                out.push_str(&format!(
                    "        if (code >= 0x{lo:02x} && code <= 0x{hi:02x}) return \"{name}\";\n"
                ));
            }
        }
        out.push_str("        return NULL;\n");
    }

    out.push_str("    default:\n");
    out.push_str("        return NULL;\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    out
}
