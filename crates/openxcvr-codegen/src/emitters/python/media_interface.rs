use crate::media_interface::MediaInterfacePlan;

pub fn emit_media_interface(plan: &MediaInterfacePlan) -> String {
    let mut out = String::new();
    out.push_str("# Generated by openxcvr-codegen. DO NOT EDIT.\n");
    out.push_str("from typing import Optional\n\n\n");
    out.push_str("def cmis_media_interface_name(media_type: int, code: int) -> Optional[str]:\n");
    out.push_str("    if not isinstance(media_type, int) or isinstance(media_type, bool):\n");
    out.push_str("        return None\n");
    out.push_str("    if not isinstance(code, int) or isinstance(code, bool):\n");
    out.push_str("        return None\n");
    out.push_str("    if not (0 <= media_type <= 255) or not (0 <= code <= 255):\n");
    out.push_str("        return None\n\n");

    for (mt, _enum_id, entries) in &plan.tables {
        out.push_str(&format!("    if media_type == 0x{mt:02x}:\n"));
        for (lo, hi, name) in entries {
            if lo == hi {
                out.push_str(&format!("        if code == 0x{lo:02x}:\n"));
                out.push_str(&format!("            return \"{name}\"\n"));
            } else {
                out.push_str(&format!("        if 0x{lo:02x} <= code <= 0x{hi:02x}:\n"));
                out.push_str(&format!("            return \"{name}\"\n"));
            }
        }
        out.push_str("        return None\n");
    }

    out.push_str("    return None\n");
    out
}
