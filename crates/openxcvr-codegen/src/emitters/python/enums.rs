use crate::ir::enums::{EntryValue, EnumSchema};
use crate::ir::naming::camel_to_snake;

pub fn emit_enum(schema: &EnumSchema) -> String {
    let class_name = &schema.id;
    let mut variants = String::new();
    let mut labels = String::new();

    for entry in &schema.entries {
        if let EntryValue::Single(v) = &entry.value {
            let variant_name = entry.name.to_uppercase();
            variants.push_str(&format!("    {variant_name} = 0x{v:02X}\n"));
            labels.push_str(&format!(
                "    {class_name}.{variant_name}: {:?},\n",
                entry.name
            ));
        }
        // Range entries are not representable as single IntEnum values — skip
    }

    if variants.is_empty() {
        variants.push_str("    pass\n");
    }

    let typing_import = if crate::emitters::enum_projection_rows(schema).is_some() {
        "from typing import Callable, Optional\n"
    } else {
        ""
    };

    format!(
        "# Generated by openxcvr-codegen. DO NOT EDIT.\nimport enum\n{typing_import}\n\nclass {class_name}(enum.IntEnum):\n{variants}\n    def label(self) -> str:\n        return _{class_name}_LABELS.get(self, self.name.lower())\n\n\n_{class_name}_LABELS = {{\n{labels}}}\n{projection}",
        projection = projection_code(schema),
    )
}

/// Revision-bound name projection functions, emitted only when the schema's
/// entries carry `since`/`until` metadata (see [`crate::emitters::enum_projection_rows`]).
/// The factory refuses out-of-range integers before any dispatch — no
/// masking, no aliasing — and each projection is a plain equality chain over
/// immutable literals, so out-of-range raws fall through to `None`.
fn projection_code(schema: &EnumSchema) -> String {
    let Some(rows) = crate::emitters::enum_projection_rows(schema) else {
        return String::new();
    };
    let snake = camel_to_snake(&schema.id);
    let rev_byte = crate::emitters::rev_byte_param(schema);
    let mut out = String::new();
    out.push_str(&format!(
        "\n\ndef {snake}_for_revision({rev_byte}: int) -> Optional[Callable[[int], Optional[str]]]:\n"
    ));
    out.push_str(&format!(
        "    if not 0 <= {rev_byte} <= 255:\n        return None\n"
    ));
    for (rev, _) in &rows {
        out.push_str(&format!(
            "    if {rev_byte} == {:#04x}:\n        return _{snake}_projection_v{}\n",
            rev.family_rev_byte(),
            rev.dirname()
        ));
    }
    out.push_str("    return None\n");
    for (rev, entries) in &rows {
        out.push_str(&format!(
            "\n\ndef _{snake}_projection_v{}(raw: int) -> Optional[str]:\n",
            rev.dirname()
        ));
        for (value, name) in entries {
            out.push_str(&format!(
                "    if raw == {value:#04x}:\n        return \"{name}\"\n"
            ));
        }
        out.push_str("    return None\n");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::enums::{EntryValue, EnumEntry, EnumSchema};

    fn make_schema() -> EnumSchema {
        EnumSchema {
            spec: None,
            provenance: None,
            description: None,
            schema: "openxcvr.enum.v2".to_string(),
            kind: "enum".to_string(),
            id: "CmisModuleState".to_string(),
            title: "Test".to_string(),
            entry_includes: vec![],
            entries: vec![
                EnumEntry {
                    name: "module_ready".to_string(),
                    value: EntryValue::Single(0x03),
                    description: None,
                    aliases: vec![],
                    tags: vec![],
                    signaling: None,
                    reach: None,
                    bit_rate_gbps: None,
                    vendor_specific: None,
                    since: None,
                    until: None,
                    changed_in: None,
                    renamed_from: None,
                    aliased_to: None,
                    provenance: None,
                },
                EnumEntry {
                    name: "reserved_6_7".to_string(),
                    value: EntryValue::Range { start: 6, end: 7 },
                    description: None,
                    aliases: vec![],
                    tags: vec![],
                    signaling: None,
                    reach: None,
                    bit_rate_gbps: None,
                    vendor_specific: None,
                    since: None,
                    until: None,
                    changed_in: None,
                    renamed_from: None,
                    aliased_to: None,
                    provenance: None,
                },
            ],
        }
    }

    #[test]
    fn emit_enum_produces_int_enum() {
        let code = emit_enum(&make_schema());
        assert!(
            code.contains("class CmisModuleState(enum.IntEnum):"),
            "missing class declaration\n---\n{code}"
        );
        assert!(
            code.contains("MODULE_READY = 0x03"),
            "missing variant\n---\n{code}"
        );
        assert!(
            !code.contains("RESERVED_6_7"),
            "Range entry must be skipped\n---\n{code}"
        );
    }

    // ── Revision-bound name projections (Task 2) ──────────────────────────

    #[test]
    fn revision_projection_is_additive_and_domain_bound() {
        let schema = crate::emitters::test_support::validated_dpsm_schema();
        let code = emit_enum(&schema);

        // Additive: the flat surface is intact.
        assert!(
            code.contains("class CmisDataPathState(enum.IntEnum):"),
            "flat class survives\n---\n{code}"
        );
        assert!(
            code.contains("DP_TX_TURN_ON = 0x05"),
            "flat member survives\n---\n{code}"
        );
        assert!(
            code.contains("def label(self) -> str:"),
            "label() survives\n---\n{code}"
        );

        // Exact public interface, with the typing import the signature needs.
        assert!(
            code.contains("from typing import Callable, Optional"),
            "typing import\n---\n{code}"
        );
        assert!(
            code.contains("def cmis_data_path_state_for_revision(cmis_rev_byte: int) -> Optional[Callable[[int], Optional[str]]]:"),
            "factory signature\n---\n{code}"
        );

        // Bounds check refuses before any dispatch: out-of-range integers are
        // never masked/coerced into a known byte.
        let factory = code
            .split("def cmis_data_path_state_for_revision")
            .nth(1)
            .unwrap()
            .split("def _cmis_data_path_state_projection")
            .next()
            .unwrap();
        assert!(
            factory.contains("if not 0 <= cmis_rev_byte <= 255:\n        return None"),
            "bounds refusal precedes dispatch\n---\n{factory}"
        );

        // Domain-bound dispatch: exactly the six packed-BCD catalog bytes.
        for (byte, rev) in [
            (0x30u8, "v3_0"),
            (0x40, "v4_0"),
            (0x50, "v5_0"),
            (0x51, "v5_1"),
            (0x52, "v5_2"),
            (0x53, "v5_3"),
            (0x54, "v5_4"),
        ] {
            assert!(
                factory.contains(&format!(
                    "cmis_rev_byte == {byte:#04x}:\n        return _cmis_data_path_state_projection_{rev}"
                )),
                "catalog byte {byte:#04x} binds its projection\n---\n{factory}"
            );
        }
        assert!(
            !factory.contains("0x55"),
            "5.5 is not a context\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x31"),
            "3.1 is not a context\n---\n{factory}"
        );

        // since/until filtering: 3.0 lacks the 4.0 names, keeps 0–4;
        // every 4.0+ projection has all eight names with canonical casing.
        let v3_0 = code
            .split("def _cmis_data_path_state_projection_v3_0")
            .nth(1)
            .unwrap()
            .split("def _cmis_data_path_state_projection_v4_0")
            .next()
            .unwrap();
        assert!(
            v3_0.contains("return \"DpActivated\""),
            "unannotated entry present at 3.0\n---\n{v3_0}"
        );
        assert!(
            !v3_0.contains("DpTxTurnOn"),
            "since 4.0 entry absent at 3.0\n---\n{v3_0}"
        );
        for rev in ["v4_0", "v5_0", "v5_1", "v5_2", "v5_3"] {
            let body = code
                .split(&format!("def _cmis_data_path_state_projection_{rev}"))
                .nth(1)
                .unwrap()
                .split("\n\n\ndef ")
                .next()
                .unwrap();
            for (value, name) in [
                (0x00u8, "Reserved0"),
                (0x01, "DpDeactivated"),
                (0x02, "DpInit"),
                (0x03, "DpDeinit"),
                (0x04, "DpActivated"),
                (0x05, "DpTxTurnOn"),
                (0x06, "DpTxTurnOff"),
                (0x07, "DpInitialized"),
            ] {
                assert!(
                    body.contains(&format!(
                        "if raw == {value:#04x}:\n        return \"{name}\""
                    )),
                    "{rev} arm {value:#04x}\n---\n{body}"
                );
            }
        }

        // No range arm: reserved 8..0xf raws stay unnamed (fall through).
        assert!(
            !code.contains("raw == 0x08"),
            "range raws unnamed\n---\n{code}"
        );
    }

    #[test]
    fn unannotated_enum_emission_is_unchanged() {
        let schema = crate::emitters::test_support::validated_unannotated_schema();
        let code = emit_enum(&schema);
        // Same enum id as the projection fixture: no entry metadata means no
        // projection surface and no typing import.
        assert!(
            !code.contains("for_revision") && !code.contains("projection"),
            "no projection items without entry metadata\n---\n{code}"
        );
        assert!(
            !code.contains("from typing import"),
            "no typing import without projection\n---\n{code}"
        );
        assert!(code.contains("class CmisDataPathState(enum.IntEnum):"));
        assert!(code.contains("def label(self) -> str:"));
    }
}
