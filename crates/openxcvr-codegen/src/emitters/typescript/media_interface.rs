use crate::media_interface::MediaInterfacePlan;

pub fn emit_media_interface(plan: &MediaInterfacePlan) -> String {
    let mut out = String::new();
    out.push_str("// Generated by openxcvr-codegen. DO NOT EDIT.\n\n");
    out.push_str("export function CmisMediaInterfaceName(mediaType: number, code: number): string | null {\n");
    out.push_str("  if (!Number.isInteger(mediaType) || !Number.isInteger(code)) return null;\n");
    out.push_str(
        "  if (mediaType < 0 || mediaType > 255 || code < 0 || code > 255) return null;\n\n",
    );
    out.push_str("  switch (mediaType) {\n");

    for (mt, _enum_id, entries) in &plan.tables {
        out.push_str(&format!("    case 0x{mt:02x}:\n"));
        for (lo, hi, name) in entries {
            if lo == hi {
                out.push_str(&format!(
                    "      if (code === 0x{lo:02x}) return \"{name}\";\n"
                ));
            } else {
                out.push_str(&format!(
                    "      if (code >= 0x{lo:02x} && code <= 0x{hi:02x}) return \"{name}\";\n"
                ));
            }
        }
        out.push_str("      return null;\n");
    }

    out.push_str("    default: return null;\n");
    out.push_str("  }\n");
    out.push_str("}\n");
    out
}
