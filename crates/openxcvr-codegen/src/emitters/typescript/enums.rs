use crate::ir::enums::{EntryValue, EnumSchema};
use crate::ir::naming::{camel_lower, camel_to_snake, NamingPolicy, TypeScriptNaming};
use std::collections::HashSet;

/// Revision-bound name projection block, emitted only when the schema's
/// entries carry `since`/`until` metadata (see [`crate::emitters::enum_projection_rows`]).
fn projection_code(schema: &EnumSchema) -> String {
    let Some(rows) = crate::emitters::enum_projection_rows(schema) else {
        return String::new();
    };
    let lower = camel_lower(&camel_to_snake(&schema.id));
    let pascal = TypeScriptNaming.type_name(&schema.id);
    let mut out = String::new();
    out.push_str(&format!(
        "\nexport type {pascal}Projection = (raw: number) => string | null;\n\n"
    ));
    let rev_byte = crate::emitters::rev_byte_param_camel(schema);
    out.push_str(&format!(
        "export function {pascal}ForRevision({rev_byte}: number): {pascal}Projection | null {{\n  switch ({rev_byte}) {{\n"
    ));
    for (rev, _) in &rows {
        out.push_str(&format!(
            "    case {:#04x}: return {lower}ProjectionV{};\n",
            rev.family_rev_byte(),
            rev.dirname()
        ));
    }
    out.push_str("    default: return null;\n  }\n}\n");
    for (rev, entries) in &rows {
        out.push_str(&format!(
            "\nfunction {lower}ProjectionV{}(raw: number): string | null {{\n  switch (raw) {{\n",
            rev.dirname()
        ));
        for (value, name) in entries {
            out.push_str(&format!("    case {value:#04x}: return \"{name}\";\n"));
        }
        out.push_str("    default: return null;\n  }\n}\n");
    }
    out
}

/// Emit a TypeScript scoped `enum` plus a `<type>Label(v)` lookup helper.
/// Per the variants are bare PascalCase (TS enums are type-scoped).
pub fn emit_enum(schema: &EnumSchema) -> String {
    let type_name = TypeScriptNaming.type_name(&schema.id);
    let mut members = String::new();
    let mut labels = String::new();
    let mut used: HashSet<String> = HashSet::new();

    for entry in &schema.entries {
        if let EntryValue::Single(v) = &entry.value {
            let mut variant = TypeScriptNaming.enum_variant(&entry.name);
            if !used.insert(variant.clone()) {
                variant = format!("{variant}Value{v:02X}");
                while !used.insert(variant.clone()) {
                    variant.push('_');
                }
            }
            members.push_str(&format!("  {variant} = 0x{v:02X},\n"));
            labels.push_str(&format!(
                "    case {type_name}.{variant}: return {:?};\n",
                entry.name
            ));
        }
        // Range entries are not representable as a single enum member — skip.
    }

    if members.is_empty() {
        // Range-only enum: no discriminants. Emit an empty enum so references
        // still resolve; the label helper falls through to "unknown".
        members.push_str("  // (range-only enum: no discrete values)\n");
    }

    format!(
        "// Generated by openxcvr-codegen. DO NOT EDIT.\n\n\
         export enum {type_name} {{\n{members}}}\n\n\
         export function {type_name}Label(v: number): string {{\n\
         \x20 switch (v) {{\n{labels}    default:\n      return \"unknown\";\n  }}\n}}\n{}",
        projection_code(schema)
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::enums::{EntryValue, EnumEntry, EnumSchema};

    fn entry(name: &str, v: u64) -> EnumEntry {
        EnumEntry {
            name: name.to_string(),
            value: EntryValue::Single(v),
            description: None,
            aliases: vec![],
            tags: vec![],
            signaling: None,
            reach: None,
            bit_rate_gbps: None,
            vendor_specific: None,
            since: None,
            until: None,
            changed_in: None,
            renamed_from: None,
            aliased_to: None,
            provenance: None,
        }
    }

    fn schema() -> EnumSchema {
        EnumSchema {
            spec: None,
            provenance: None,
            description: None,
            schema: "openxcvr.enum.v2".to_string(),
            kind: "enum".to_string(),
            id: "CmisModuleState".to_string(),
            title: "Module State".to_string(),
            entry_includes: vec![],
            entries: vec![entry("module_low_pwr", 0x01), entry("module_ready", 0x03)],
        }
    }

    #[test]
    fn emits_scoped_enum_and_label() {
        let out = emit_enum(&schema());
        assert!(out.contains("export enum CmisModuleState {"), "{out}");
        assert!(out.contains("ModuleLowPwr = 0x01,"), "{out}");
        assert!(out.contains("ModuleReady = 0x03,"), "{out}");
        assert!(
            out.contains("export function CmisModuleStateLabel(v: number): string"),
            "{out}"
        );
        assert!(
            out.contains("case CmisModuleState.ModuleReady: return \"module_ready\";"),
            "{out}"
        );
    }

    #[test]
    fn revision_projection_is_additive_and_domain_bound() {
        let schema = crate::emitters::test_support::validated_dpsm_schema();
        let out = emit_enum(&schema);

        assert!(
            out.contains(
                "export type CmisDataPathStateProjection = (raw: number) => string | null;"
            ),
            "projection type alias\n---\n{out}"
        );
        assert!(
            out.contains(
                "export function CmisDataPathStateForRevision(cmisRevByte: number): CmisDataPathStateProjection | null {"
            ),
            "factory signature\n---\n{out}"
        );

        let factory = out
            .split("export function CmisDataPathStateForRevision")
            .nth(1)
            .unwrap()
            .split("function cmisDataPathStateProjectionV3_0")
            .next()
            .unwrap();
        for (byte, rev) in [
            (0x30u8, "V3_0"),
            (0x40, "V4_0"),
            (0x50, "V5_0"),
            (0x51, "V5_1"),
            (0x52, "V5_2"),
            (0x53, "V5_3"),
            (0x54, "V5_4"),
        ] {
            assert!(
                factory.contains(&format!(
                    "case {byte:#04x}: return cmisDataPathStateProjection{rev};"
                )),
                "catalog byte {byte:#04x} binds its projection\n---\n{factory}"
            );
        }
        assert!(
            factory.contains("default: return null;"),
            "refusal branch\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x55"),
            "5.5 is not a context\n---\n{factory}"
        );
        assert!(
            !factory.contains("0x31"),
            "3.1 is not a context\n---\n{factory}"
        );

        let v3_0 = out
            .split("function cmisDataPathStateProjectionV3_0")
            .nth(1)
            .unwrap()
            .split("function ")
            .next()
            .unwrap();
        assert!(
            v3_0.contains("case 0x04: return \"DpActivated\";"),
            "unannotated entry present at 3.0\n---\n{v3_0}"
        );
        assert!(
            !v3_0.contains("DpTxTurnOn"),
            "since 4.0 entry absent at 3.0\n---\n{v3_0}"
        );

        for rev in ["V4_0", "V5_0", "V5_1", "V5_2", "V5_3"] {
            let body = out
                .split(&format!("function cmisDataPathStateProjection{rev}"))
                .nth(1)
                .unwrap();
            for (value, name) in [
                (0x00u8, "Reserved0"),
                (0x01, "DpDeactivated"),
                (0x02, "DpInit"),
                (0x03, "DpDeinit"),
                (0x04, "DpActivated"),
                (0x05, "DpTxTurnOn"),
                (0x06, "DpTxTurnOff"),
                (0x07, "DpInitialized"),
            ] {
                assert!(
                    body.contains(&format!("case {value:#04x}: return \"{name}\";")),
                    "{rev} arm {value:#04x}\n---\n{body}"
                );
            }
        }

        assert!(
            !out.contains("case 0x08:"),
            "range raws unnamed\n---\n{out}"
        );
    }

    #[test]
    fn unannotated_enum_emission_is_unchanged() {
        let schema = crate::emitters::test_support::validated_unannotated_schema();
        let out = emit_enum(&schema);
        assert!(
            !out.contains("Projection"),
            "no projection items without entry metadata\n---\n{out}"
        );
        assert!(
            !out.contains("ForRevision"),
            "no revision factory without entry metadata\n---\n{out}"
        );
    }
}
