use crate::media_interface::MediaInterfacePlan;

pub fn emit_media_interface(plan: &MediaInterfacePlan) -> String {
    let mut out = String::new();
    out.push_str("// Generated by openxcvr-codegen. DO NOT EDIT.\n\n");
    out.push_str("package enums\n\n");
    out.push_str("func CmisMediaInterfaceName(mediaType, code byte) (string, bool) {\n");
    out.push_str("\tswitch mediaType {\n");

    for (mt, _enum_id, entries) in &plan.tables {
        out.push_str(&format!("\tcase 0x{mt:02x}:\n"));
        out.push_str("\t\tswitch {\n");
        for (lo, hi, name) in entries {
            if lo == hi {
                out.push_str(&format!("\t\tcase code == 0x{lo:02x}:\n"));
                out.push_str(&format!("\t\t\treturn \"{name}\", true\n"));
            } else {
                out.push_str(&format!(
                    "\t\tcase code >= 0x{lo:02x} && code <= 0x{hi:02x}:\n"
                ));
                out.push_str(&format!("\t\t\treturn \"{name}\", true\n"));
            }
        }
        out.push_str("\t\tdefault:\n");
        out.push_str("\t\t\treturn \"\", false\n");
        out.push_str("\t\t}\n");
    }

    out.push_str("\tdefault:\n");
    out.push_str("\t\treturn \"\", false\n");
    out.push_str("\t}\n");
    out.push_str("}\n");
    super::format_go(&out)
}
