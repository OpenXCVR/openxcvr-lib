    #[test]
    fn test_emit_enum_basic() {
        let schema = make_schema();
        let out = emit_enum(&schema);
        assert!(
            out.contains("type CmisModuleState int"),
            "missing type declaration\n---\n{out}"
        );
        assert!(
            out.contains("CmisModuleStateModuleReady CmisModuleState = 0x03"),
            "missing const\n---\n{out}"
        );
        assert!(
            !out.contains("Reserved6"),
            "range entries should be skipped\n---\n{out}"
        );
        assert!(
            out.starts_with("// Generated by openxcvr-codegen. DO NOT EDIT."),
            "missing header\n---\n{out}"
        );
        assert!(
            out.contains("package enums"),
            "missing package declaration\n---\n{out}"
        );
    }

