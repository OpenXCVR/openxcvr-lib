use crate::ir::enums::{EntryValue, EnumSchema};
use crate::ir::naming::{camel_lower, camel_to_snake, GoNaming, NamingPolicy};
use std::collections::HashSet;

/// The Go raw-value type for an enum's value magnitude (byte for DPSM-style
/// nibble/byte enums).
fn raw_go_type(schema: &EnumSchema) -> &'static str {
    let max = schema
        .entries
        .iter()
        .filter_map(|e| e.value.as_single())
        .max()
        .unwrap_or(0);
    if max <= 0xFF {
        "byte"
    } else if max <= 0xFFFF {
        "uint16"
    } else {
        "uint32"
    }
}

/// Revision-bound name projection block, emitted only when the schema's
/// entries carry `since`/`until` metadata (see [`crate::emitters::enum_projection_rows`]).
fn projection_code(schema: &EnumSchema) -> String {
    let Some(rows) = crate::emitters::enum_projection_rows(schema) else {
        return String::new();
    };
    // Unexported Go identifiers are lowerCamelCase (camel_lower of the snake
    // form), e.g. cmisDataPathStateProjectionV3_0.
    let lower = camel_lower(&camel_to_snake(&schema.id));
    let pascal = GoNaming.type_name(&schema.id);
    let raw = raw_go_type(schema);
    let mut out = String::new();
    out.push_str(&format!(
        "\ntype {pascal}Projection func(raw {raw}) (string, bool)\n\n"
    ));
    let rev_byte = crate::emitters::rev_byte_param_camel(schema);
    out.push_str(&format!(
        "func {pascal}ForRevision({rev_byte} byte) ({pascal}Projection, bool) {{\n\tswitch {rev_byte} {{\n"
    ));
    for (rev, _) in &rows {
        out.push_str(&format!(
            "\tcase {:#04x}:\n\t\treturn {lower}ProjectionV{}, true\n",
            rev.family_rev_byte(),
            rev.dirname()
        ));
    }
    out.push_str("\tdefault:\n\t\treturn nil, false\n\t}\n}\n");
    for (rev, entries) in &rows {
        out.push_str(&format!(
            "\nfunc {lower}ProjectionV{}(raw {raw}) (string, bool) {{\n\tswitch raw {{\n",
            rev.dirname()
        ));
        for (value, name) in entries {
            out.push_str(&format!(
                "\tcase {value:#04x}:\n\t\treturn \"{name}\", true\n"
            ));
        }
        out.push_str("\tdefault:\n\t\treturn \"\", false\n\t}\n}\n");
    }
    out
}

pub fn emit_enum(schema: &EnumSchema) -> String {
    let type_name = &schema.id;
    let mut entries_to_emit = Vec::new();
    let mut labels = String::new();
    let mut used_suffixes = HashSet::new();

    for entry in &schema.entries {
        if let EntryValue::Single(v) = &entry.value {
            let mut suffix = GoNaming.enum_variant(&entry.name);
            if !used_suffixes.insert(suffix.clone()) {
                suffix = format!("{suffix}Value{v:02X}");
                while !used_suffixes.insert(suffix.clone()) {
                    suffix.push('_');
                }
            }
            let const_name = format!("{type_name}{suffix}");
            labels.push_str(&format!(
                "\tcase {const_name}:\n\t\treturn {:?}\n",
                entry.name
            ));
            entries_to_emit.push((const_name, *v));
        }
        // Range entries are not representable as a single typed const — skip
    }

    if entries_to_emit.is_empty() {
        return super::format_go(&format!(
            "// Generated by openxcvr-codegen. DO NOT EDIT.\npackage enums\n\ntype {type_name} int\n{}",
            projection_code(schema)
        ));
    }

    let max_name_len = entries_to_emit
        .iter()
        .map(|(n, _)| n.len())
        .max()
        .unwrap_or(0);
    let mut consts = String::new();
    for (const_name, v) in entries_to_emit {
        let pad = " ".repeat(max_name_len - const_name.len() + 1);
        consts.push_str(&format!("\t{const_name}{pad}{type_name} = 0x{v:02X}\n"));
    }

    super::format_go(&format!(
        "// Generated by openxcvr-codegen. DO NOT EDIT.\npackage enums\n\ntype {type_name} int\n\nconst (\n{consts})\n\nfunc (v {type_name}) Label() string {{\n\tswitch v {{\n{labels}\tdefault:\n\t\treturn \"unknown\"\n\t}}\n}}\n{}",
        projection_code(schema)
    ))
}

